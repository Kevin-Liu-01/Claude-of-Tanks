/** Publish the measured curves on the registry's specs (after every spec pack has registered). */
export function applyTurretScaleGunPitch(registry: TankSpecRegistry): void {
  for (const [id, curve] of Object.entries(TURRET_SCALE_GUN_PITCH_BY_YAW)) {
    const spec = registry[id];
    if (!spec) throw new Error(`turretScaleGunPitch: unknown tank ${id}`);
    spec.gunPitchByYawDeg = curve;
  }
}
