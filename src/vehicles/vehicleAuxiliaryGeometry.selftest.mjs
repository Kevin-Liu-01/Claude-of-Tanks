import assert from 'node:assert/strict';
import * as THREE from 'three';
import {markSmokeTube,markOpenSmokeTube,registerSmokeSockets,smokeSocketsFor,alignSmokeBanks} from './vehicleAuxiliaryGeometry.ts';
const closed=markSmokeTube(new THREE.CylinderGeometry(.1,.1,.4,12).rotateX(Math.PI/2));
closed.rotateX(-.4).translate(.6,.2,1);
const mesh=new THREE.Mesh(closed);registerSmokeSockets(mesh,[closed]);
const socket=smokeSocketsFor(mesh)[0];assert.ok(socket.direction[1]>.38 && socket.direction[2]>.9);
assert.ok(socket.position[2]>1.18,'socket follows the actual transformed forward cap');
const open=markOpenSmokeTube(new THREE.CylinderGeometry(.1,.1,.4,12,1,true).rotateX(Math.PI/2));
open.rotateY(.6).scale(2,2,2).translate(1,0,0);
const openMesh=new THREE.Mesh(open);registerSmokeSockets(openMesh,[open]);
assert.ok(Math.abs(smokeSocketsFor(openMesh)[0].direction[0]-Math.sin(.6))<1e-6);
const root=new THREE.Group(),turret=new THREE.Group(),bank=new THREE.Group();turret.name='rig_turret';root.add(turret);turret.add(bank);bank.add(mesh);
bank.userData={fittingRoot:true,fitting:'smokeBank'};bank.rotation.y=2;
alignSmokeBanks(root);root.updateMatrixWorld(true);
const direction=new THREE.Vector3(...socket.direction).transformDirection(mesh.matrixWorld);
assert.ok(direction.z>0,'complete bank alignment cannot leave rearward apertures');
assert.equal(mesh.geometry,closed,'alignment preserves authored geometry');
closed.dispose();open.dispose();
console.log('vehicleAuxiliaryGeometry: transformed closed/open apertures and complete bank alignment pass');
