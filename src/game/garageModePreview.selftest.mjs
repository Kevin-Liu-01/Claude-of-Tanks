import assert from 'node:assert/strict';
import * as T from 'three';
import { createGarageModePreview } from './garageModePreview.ts';
import { syncJuggernautVisual, pulseJuggernautImpact, clearJuggernautVisual, prepareGarageTankEnergyVisual } from './juggernautVisual.ts';
import '../vehicles/tankFactory.ts';
import { TANK_SPECS } from '../vehicles/specs.ts';
import { missionAttachmentFor } from '../sim/missionAttachment.ts';
const preview=createGarageModePreview();
const geometry=new T.BoxGeometry(), paint=new T.MeshStandardMaterial();
function tank(id){
 const root=new T.Group(),turret=new T.Group(),mesh=new T.Mesh(geometry,paint);
 turret.name='rig_turret';root.add(mesh,turret);return {root,mesh,spec:TANK_SPECS[id]};
}
for(const id of ['m1a2','kf41_lynx_x','strv103']){
 const a=tank(id),b=tank(id);
 preview.update(a.root,a.spec,'juggernaut',.016);
 assert.notEqual(a.mesh.material,paint);
 assert.equal(a.root.scale.x,1,'showroom keeps its calibrated floor seating');
 preview.update(b.root,b.spec,'juggernaut',.016);
 const dormant={uniforms:{},vertexShader:T.ShaderLib.standard.vertexShader,fragmentShader:T.ShaderLib.standard.fragmentShader};
 a.mesh.material.onBeforeCompile(dormant,{});
 assert.equal(dormant.uniforms.juggernautStrength.value,0,'cached previous tank loses its glow while retaining its compiled skin');
 assert.notEqual(b.mesh.material,paint,'new selection gets energy');
 const compiled=b.mesh.material;
 preview.update(b.root,b.spec,'capture_the_flag',.016);
 assert.equal(b.mesh.material,compiled,'flag uses the existing compiled energy material');
 assert.equal(preview.update(b.root,b.spec,'infected',.016),false,'uniform-only mode changes need no shader warm');
 assert.equal(b.mesh.material,compiled,'infection changes uniforms, not shader programs');
 assert.equal(b.root.getObjectByName('Capture flag assembly'),undefined);
 preview.update(b.root,b.spec,'drone',.016);
 assert.equal(b.mesh.material,compiled,'leaving aura modes retains the compiled preview material');
 const pausedShader={uniforms:{},vertexShader:T.ShaderLib.standard.vertexShader,fragmentShader:T.ShaderLib.standard.fragmentShader};
 compiled.onBeforeCompile(pausedShader,{});
 assert.equal(pausedShader.uniforms.juggernautStrength.value,0,'ordinary modes show original paint');
 assert.doesNotMatch(pausedShader.fragmentShader,/rippleWarp|exp\(-pow/,'garage omits combat impact calculations');
 const rail=b.root.getObjectByName('Reusable mission payload rail');
 assert.ok(rail.getObjectByName('Docked FPV mission payload').visible);
 const seat=missionAttachmentFor(b.spec);
 assert.equal(rail.parent,seat.frame==='turret'?b.root.getObjectByName('rig_turret'):b.root);
 preview.update(b.root,b.spec,'capture_the_flag',.016);
 assert.equal(b.root.getObjectByName('Docked FPV mission payload'),undefined);
 assert.ok(b.root.getObjectByName('Capture flag assembly'));
 const banner=b.root.getObjectByName('Woven team banner');
 const shader={uniforms:{},vertexShader:T.ShaderLib.standard.vertexShader,fragmentShader:T.ShaderLib.standard.fragmentShader};
 banner.material.onBeforeCompile(shader,{});
 const time=shader.uniforms.flagTime.value;
 preview.update(b.root,b.spec,'capture_the_flag',.04);
 assert.ok(shader.uniforms.flagTime.value>time,'cloth animation advances');
 assert.match(shader.vertexShader,/objectNormal = normalize/,'lighting follows cloth deformation');
 preview.update(b.root,b.spec,'infected',.016);
 assert.equal(b.mesh.material.name,'Infected surface highlight');
 assert.equal(b.root.getObjectByName('Capture flag assembly'),undefined);
 preview.update(b.root,b.spec,'standard',.016);
 assert.equal(b.root.getObjectByName('Reusable mission payload rail'),undefined);
 assert.equal(preview.update(b.root,b.spec,'juggernaut',.016),false,'return to a resident aura needs no shader warm');
 assert.equal(b.mesh.material,compiled);
 assert.ok(pausedShader.uniforms.juggernautStrength.value>0);
 let disposed=0;compiled.addEventListener('dispose',()=>disposed++);
 preview.clear();
 assert.equal(disposed,1,'clearing the tank releases retained preview materials');
 assert.equal(b.mesh.material,paint,'entry hands a clean vehicle to battle');
 preview.update(b.root,b.spec,'juggernaut',.016);
 assert.notEqual(b.mesh.material,paint,'return recreates selected-mode preview');
 preview.clear();preview.clear();
}
const direct=tank('m1a2');
preview.update(direct.root,direct.spec,'juggernaut',0);
const garageMaterial=direct.mesh.material;
syncJuggernautVisual(direct.root,{widthM:3,hullLengthM:7,heightM:2.6},1.12,100,100,0);
assert.notEqual(direct.mesh.material,garageMaterial,'battle upgrades the simplified preview shader');
assert.equal(pulseJuggernautImpact(direct.root,[0,1,0]),true,'battle retains impact ripples');
clearJuggernautVisual(direct.root);preview.clear();
// The first menu click must reuse the exact material prepared with the vehicle.
const cold=tank('m1a2');
prepareGarageTankEnergyVisual(cold.root,cold.spec.dims);
const readyPaint=cold.mesh.material;
const coldShader={uniforms:{},vertexShader:T.ShaderLib.standard.vertexShader,fragmentShader:T.ShaderLib.standard.fragmentShader};
readyPaint.onBeforeCompile(coldShader,{});
assert.equal(coldShader.uniforms.juggernautStrength.value,0,'initial skin is visually dormant');
paint.color.setHex(0x345678);
assert.equal(readyPaint.color.getHex(),0x345678,'dormant skin follows camouflage fitting retints');
assert.equal(readyPaint.map,paint.map,'camouflage texture upload remains shared');
assert.equal(preview.update(cold.root,cold.spec,'juggernaut',0),false,'first selection requires no new shader preparation');
assert.equal(cold.mesh.material,readyPaint,'first selection does not replace prepared materials');
assert.ok(coldShader.uniforms.juggernautStrength.value>0,'already-bound uniforms enable the effect');
const scene=new T.Scene();scene.add(cold.root);scene.remove(cold.root);
assert.equal(cold.mesh.material,readyPaint,'parking a cached hero retains its compiled skin');
preview.update(null,null,'standard',0);
assert.equal(coldShader.uniforms.juggernautStrength.value,0,'parked skin stops glowing');
scene.add(cold.root);
assert.equal(preview.update(cold.root,cold.spec,'juggernaut',0),false,'returning to a cached hero never relinks');
preview.clear();
const discarded=tank('m1a2');
prepareGarageTankEnergyVisual(discarded.root,discarded.spec.dims);
const discardedPaint=discarded.mesh.material;let released=0;
discardedPaint.addEventListener('dispose',()=>released++);
paint.dispose();
assert.equal(released,1,'disposing a cached vehicle source releases its dormant material');
assert.equal(discarded.mesh.material,paint,'eviction restores the source before cleanup');
geometry.dispose();paint.dispose();
console.log('garageModePreview: tank changes, turret/hull mounts, mode changes, cloth animation and clean battle/return lifecycle pass');
