import assert from 'node:assert/strict';
import { BattleKillLedger, FiredRoundLedger } from './battleEventStats.ts';
const kills = new BattleKillLedger();
assert.equal(kills.record('enemy-1', 'ally-1', 'red', 'green'), true);
assert.equal(kills.record('enemy-1', 'ally-1', 'red', 'green'), false);
assert.equal(kills.count('ally-1'), 1);
kills.record('ally-2', 'ally-1', 'green', 'green');
kills.record('ally-1', 'ally-1', 'green', 'green');
assert.equal(kills.count('ally-1'), 1, 'friendly fire and suicide are not enemy kills');
kills.respawn('enemy-1');kills.record('enemy-1', 'ally-1', 'red', 'green');
assert.equal(kills.count('ally-1'), 2, 'respawn re-arms destruction without clearing scores');
kills.record('same-model-different-entity', 'ally-2', 'red', 'green');
assert.equal(kills.count('ally-2'), 1);
kills.clear();assert.equal(kills.count('ally-1'), 0);
const rounds = new FiredRoundLedger();
rounds.fire(1);
assert.deepEqual(rounds.hit(1, false), {hit:true,pen:false});
assert.deepEqual(rounds.hit(1, true), {hit:false,pen:true}, 'a later penetrating target still marks round as penetrating');
assert.deepEqual(rounds.hit(1, true), {hit:false,pen:false}, 'splash cannot inflate either count');
assert.deepEqual(rounds.hit(20, true), {hit:false,pen:false}, 'drone with no fired round is excluded');
assert.deepEqual(rounds.hit(undefined, true), {hit:false,pen:false}, 'ram/fire are not rounds');
rounds.fire();assert.deepEqual(rounds.hit(undefined, true), {hit:true,pen:true});
assert.deepEqual(rounds.hit(undefined, true), {hit:false,pen:false});
rounds.clear();assert.deepEqual(rounds.hit(1, true), {hit:false,pen:false});
console.log('battleEventStats: attribution, duplicate events, respawns, friendly fire, and unique-round accuracy PASS');
