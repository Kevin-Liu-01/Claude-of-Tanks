export const EARTH_MASK_WIDTH = 1024;
export const EARTH_MASK_HEIGHT = 512;

/** The rings' coverage of each texel (even-odd; two sample rows and two sample columns a texel, a quarter each). */
function fillRings(coverage: Float32Array, rings: readonly Ring[], value: number): void {
  const W = EARTH_MASK_WIDTH, H = EARTH_MASK_HEIGHT, step = value > 0 ? 0.25 : -0.25;
  const xs = new Float64Array(256);
  // each ring flat (x, y pairs) with its latitude range, so a row only walks the rings that cross it
  const flat = rings.map((ring) => {
    const pts = new Float64Array(ring.length * 2);
    let lo = Infinity, hi = -Infinity;
    ring.forEach(([x, y], i) => { pts[i * 2] = x; pts[i * 2 + 1] = y; lo = Math.min(lo, y); hi = Math.max(hi, y); });
    return { pts, lo, hi };
  });
  for (let row = 0; row < H * 2; row++) {
    const lat = 90 - ((row + 0.5) / (H * 2)) * 180, base = (row >> 1) * W;
    for (const { pts, lo, hi } of flat) {
      if (lat < lo || lat > hi) continue;
      let n = 0;
      const m = pts.length;
      for (let i = 0, j = m - 2; i < m; j = i, i += 2) {
        const yi = pts[i + 1], yj = pts[j + 1];
        if ((yi > lat) !== (yj > lat)) xs[n++] = pts[i] + ((lat - yi) / (yj - yi)) * (pts[j] - pts[i]);
      }
      if (n < 2) continue;
      const hits = xs.subarray(0, n).sort();
      for (let k = 0; k + 1 < n; k += 2) {
        // the sample columns (texel x's two at x + 0.25 and x + 0.75: sample s at (s + 0.5) / 2) inside the span
        const s0 = Math.max(0, Math.ceil(((hits[k] + 180) / 360) * W * 2 - 0.5));
        const s1 = Math.min(W * 2 - 1, Math.ceil(((hits[k + 1] + 180) / 360) * W * 2 - 0.5) - 1);
        for (let sIdx = s0; sIdx <= s1; sIdx++) coverage[base + (sIdx >> 1)] += step;
      }
    }
  }
}

/** The land's coverage, one byte a texel (0 sea, 255 land), rows from the north pole down, columns from 180° W. */
export function rasteriseEarthLand(): Uint8Array {
  const coverage = new Float32Array(EARTH_MASK_WIDTH * EARTH_MASK_HEIGHT);
  fillRings(coverage, EARTH_LAND, 1);
  fillRings(coverage, EARTH_INLAND_SEAS, -1);
  const bytes = new Uint8Array(coverage.length);
  for (let i = 0; i < coverage.length; i++) bytes[i] = Math.round(Math.min(1, Math.max(0, coverage[i])) * 255);
  return bytes;
}

let landTexture: THREE.DataTexture | null = null;
/** The land mask as a linear-filtered single-channel texture (built once, on first use). */
export function earthLandTexture(): THREE.DataTexture {
  if (!landTexture) {
    landTexture = new THREE.DataTexture(rasteriseEarthLand(), EARTH_MASK_WIDTH, EARTH_MASK_HEIGHT, THREE.RedFormat, THREE.UnsignedByteType);
    landTexture.wrapS = THREE.RepeatWrapping;
    landTexture.wrapT = THREE.ClampToEdgeWrapping;
    landTexture.magFilter = THREE.LinearFilter;
    landTexture.minFilter = THREE.LinearMipmapLinearFilter;
    landTexture.generateMipmaps = true;
    landTexture.flipY = false;
    landTexture.needsUpdate = true;
  }
  return landTexture;
}
