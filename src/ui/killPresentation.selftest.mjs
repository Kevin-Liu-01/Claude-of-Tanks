const base={victimId:'e',killerId:'me',playerId:'me',killerTeam:'allies',victimTeam:'enemy'};
assert.equal(killPresentation(base).relation,'you');
assert.equal(killPresentation({victimId:'enemy'}).relation,null,'no player identity must not imply your kill');
assert.equal(killPresentation({...base,cause:'ammorack',drone:true}).icon,'ammoRack');
assert.equal(killPresentation({...base,drone:true}).icon,'modeDrone');
assert.equal(killPresentation({...base,cause:'ram'}).icon,'killRam');
assert.equal(killPresentation({...base,victimTeam:'allies'}).relation,'friendly');
assert.equal(killPresentation({...base,victimId:'me'}).relation,'self');
assert.equal(killPresentation({...base,killerId:'e',victimId:'me'}).relation,'victim');
assert.equal(isDroneStrike({shellName:'FPV shaped charge'}),true);
assert.equal(isDroneStrike({shellName:'HEAT'}),false);
assert.equal(battleMapArt('winter'),'/maps/winter.webp');
assert.equal(battleMapArt('winter',true),'/maps/thumbs/winter.webp');
for(const id of ['missing','__proto__','constructor','\" onclick=bad','Glacier Pass',null])assert.equal(battleMapArt(id),null);
