// The only packed runtime geometry admitted by the provenance audit is the
// generated interior-fill box format. It contains voxel spans, never arbitrary
// vertices, indices, materials, executable expressions or source-model payloads.
import ts from 'typescript-compiler-api';

const DATA_PATH = /^src\/vehicles\/interiorFillGroups\/[A-Za-z0-9]+\.generated\.ts$/;
const READER_PATH = 'src/vehicles/interiorFills.ts';
const DECODER = `function decodeSextets(encoded: string): Uint16Array {
  const binary = atob(encoded);
  const out = new Uint16Array(binary.length >> 1);
  for (let i = 0; i < out.length; i++) out[i] = binary.charCodeAt(2 * i) | (binary.charCodeAt(2 * i + 1) << 8);
  return out;
}`;
const compact = source => source.replace(/\s+/g, '');

function numeric(node) {
  if (ts.isNumericLiteral(node)) return Number(node.text);
  if (ts.isPrefixUnaryExpression(node) && node.operator === ts.SyntaxKind.MinusToken
      && ts.isNumericLiteral(node.operand)) return -Number(node.operand.text);
  throw new Error('fill metadata must be literal numbers');
}

function vector(node) {
  if (!ts.isArrayLiteralExpression(node) || node.elements.length !== 3) {
    throw new Error('fill frame must contain three numbers');
  }
  const values = node.elements.map(numeric);
  if (values.some(value => !Number.isFinite(value) || Math.abs(value) > 64)) {
    throw new Error('fill frame exceeds the vehicle envelope');
  }
  return values;
}

function validateSpans(encoded, voxel, origin) {
  if (!/^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/.test(encoded)) {
    throw new Error('fill spans have invalid base64');
  }
  const bytes = Buffer.from(encoded, 'base64');
  if (bytes.length % 12 || bytes.toString('base64') !== encoded) {
    throw new Error('fill spans must be complete canonical Uint16 sextets');
  }
  for (let offset = 0; offset < bytes.length; offset += 12) {
    for (let axis = 0; axis < 3; axis++) {
      const low = bytes.readUInt16LE(offset + axis * 2);
      const high = bytes.readUInt16LE(offset + (axis + 3) * 2);
      if (low > high || (high + 1) * voxel > 64
          || origin[axis] + low * voxel < -64 || origin[axis] + (high + 1) * voxel > 64) {
        throw new Error('fill span must be an ordered box inside a vehicle-sized grid');
      }
    }
  }
}

/** Parse data without executing a generated module or trusting its filename. */
export function validateInteriorFillModule(source) {
  const properties = fillRecordProperties(source);
  const ids = new Set();
  let count = 0;
  for (const row of properties) {
    count += validateFillRow(row, ids);
  }
  return { vehicleCount: ids.size, componentCount: count };
}

/** Return only the text still subject to generic encoded-mesh rejection. */
export function sourceAfterInteriorFillValidation(relativePath, source) {
  if (DATA_PATH.test(relativePath)) {
    validateInteriorFillModule(source);
    // The entire module was parsed under the box-only grammar above.
    return '';
  }
  if (relativePath === READER_PATH) {
    const ast = ts.createSourceFile('reader.ts', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
    const decoder = ast.statements.find(node => ts.isFunctionDeclaration(node) && node.name?.text === 'decodeSextets');
    if (!decoder || compact(decoder.getText(ast)) !== compact(DECODER)) {
      throw new Error('interior-fill decoder changed; review its box-only contract');
    }
    // Other decoders or packed literals in the reader still fail the normal audit.
    return source.slice(0, decoder.getStart(ast)) + source.slice(decoder.end);
  }
  return source;
}

function fillRecordProperties(source) {
  if (!source.startsWith('// Generated by tools/gen-interior-fills.mjs. Do not hand-edit.')) {
    throw new Error('missing interior-fill generator contract');
  }
  const ast = ts.createSourceFile('fill.ts', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  if (ast.parseDiagnostics.length || ast.statements.length !== 2) {
    throw new Error('fill module must contain only its type import and data export');
  }
  const [typeImport, statement] = ast.statements;
  if (!ts.isImportDeclaration(typeImport) || !typeImport.importClause?.isTypeOnly
      || typeImport.moduleSpecifier.text !== '../interiorFills.ts'
      || !ts.isVariableStatement(statement)
      || !(statement.declarationList.flags & ts.NodeFlags.Const)
      || !statement.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)
      || statement.declarationList.declarations.length !== 1) {
    throw new Error('unexpected executable interior-fill module content');
  }
  const declaration = statement.declarationList.declarations[0];
  const call = declaration.initializer;
  if (declaration.name.getText(ast) !== 'INTERIOR_FILLS' || !call || !ts.isCallExpression(call)
      || call.expression.getText(ast) !== 'Object.freeze' || call.arguments.length !== 1
      || !ts.isObjectLiteralExpression(call.arguments[0])) {
    throw new Error('fill export must be a frozen literal record');
  }
  return call.arguments[0].properties;
}

function fillValues(row) {
    const values = new Map();
    for (const property of row.initializer.properties) {
      if (!ts.isPropertyAssignment(property) || !ts.isIdentifier(property.name)
          || values.has(property.name.text)) throw new Error('invalid fill property');
      const key = property.name.text;
      if (!['v', 'o', 't', 'g', 'hull', 'turret', 'gun'].includes(key)) {
        throw new Error(`unexpected fill property: ${key}`);
      }
      values.set(key, property.initializer);
    }
    return values;
}

function validateFillRow(row, ids) {
  let count = 0;
    if (!ts.isPropertyAssignment(row) || !ts.isStringLiteral(row.name)
        || !/^[a-z0-9_]+$/.test(row.name.text) || row.name.text === '__proto__' || ids.has(row.name.text)
        || !ts.isObjectLiteralExpression(row.initializer)) {
      throw new Error('fill entries must have unique literal vehicle IDs');
    }
    ids.add(row.name.text);
    const values = fillValues(row);
    if (!values.has('v') || !values.has('o') || !values.has('t')) throw new Error('missing fill frame');
    const voxel = numeric(values.get('v'));
    if (!(voxel > 0 && voxel <= .1)) throw new Error('invalid fill voxel size');
    for (const key of ['o', 't', 'g']) if (values.has(key)) vector(values.get(key));
    for (const key of ['hull', 'turret', 'gun']) {
      if (!values.has(key)) continue;
      const node = values.get(key);
      if (!ts.isStringLiteral(node)) throw new Error('fill spans must be literal data');
      validateSpans(node.text, voxel, vector(values.get('o')));
      count++;
    }
  return count;
}
