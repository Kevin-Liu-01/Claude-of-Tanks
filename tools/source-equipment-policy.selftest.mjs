import {BARAK_SOURCE_CONFIGURATION} from './barak-source-openings.mjs';
import assert from 'node:assert/strict';
import * as THREE from 'three';
import {censusEquipment,roofEquipmentVerdict} from './source-equipment-policy.mjs';
const id='fixture_x', source={path:'public/models/community-candidates/fixture_x_source.glb',sha256:'a'.repeat(64)};
const receipt={id,verified:true,...source};
const config=count=>({id,source,roofMachineGuns:count});
const verdict=(census,configuration,verified)=>roofEquipmentVerdict(id,census,configuration,verified?receipt:null);
const root=new THREE.Group(), fitting=new THREE.Group();
fitting.userData={fittingRoot:true,fitting:'pintleMG'};root.add(fitting);
assert.equal(censusEquipment(root).invalidWeaponMarkers,1,'empty fitting labels are not weapons');
assert.equal(verdict(censusEquipment(root),config(0),true).passed,false);
const stock=new THREE.Mesh(new THREE.BoxGeometry(.1,.1,.2),new THREE.MeshBasicMaterial());fitting.add(stock);
assert.equal(censusEquipment(root).mg,1,'real visible fitting stock enters census');
assert.equal(verdict(censusEquipment(root),undefined).passed,true,'unregistered fleet requirement preserved');
assert.equal(verdict(censusEquipment(root),config(1),true).passed,true);
assert.equal(verdict(censusEquipment(root),config(0),true).passed,false,'invented roof fitting violates supplied configuration');
for(const [object,property,value]of[[stock,'visible',false],[stock.material,'visible',false],[stock.material,'colorWrite',false]]){
 const before=object[property];object[property]=value;
 assert.equal(censusEquipment(root).invalidWeaponMarkers,1,'hidden/helper stock cannot validate weapon marker');object[property]=before;
}
stock.material.transparent=true;stock.material.opacity=0;
assert.equal(censusEquipment(root).invalidWeaponMarkers,1,'transparent zero-opacity stock does not draw a weapon');
stock.material.transparent=false;stock.material.opacity=1;
stock.geometry.setDrawRange(0,0);
assert.equal(censusEquipment(root).invalidWeaponMarkers,1,'empty draw range cannot validate a weapon');
stock.geometry.setDrawRange(0,Infinity);
const goodGeometry=stock.geometry;
stock.geometry=new THREE.BufferGeometry();stock.geometry.setAttribute('position',new THREE.Float32BufferAttribute([0,0,0,0,0,0,0,0,0],3));
assert.equal(censusEquipment(root).invalidWeaponMarkers,1,'degenerate triangles are empty stock');stock.geometry.dispose();stock.geometry=goodGeometry;
const goodMaterial=stock.material, hiddenMaterial=new THREE.MeshBasicMaterial({visible:false});
stock.material=[hiddenMaterial,goodMaterial];const originalGroups=stock.geometry.groups.map(g=>({...g}));
stock.geometry.clearGroups();stock.geometry.addGroup(0,stock.geometry.index.count,0);
assert.equal(censusEquipment(root).invalidWeaponMarkers,1,'unused visible material slots cannot validate hidden drawn groups');
stock.geometry.groups=originalGroups;stock.material=goodMaterial;hiddenMaterial.dispose();
stock.scale.setScalar(0);
assert.equal(censusEquipment(root).invalidWeaponMarkers,1,'collapsed world stock cannot validate a weapon');stock.scale.setScalar(1);
const validPosition=stock.geometry.attributes.position.array[0];stock.geometry.attributes.position.array[0]=Infinity;
// Make every triangle malformed, not just one face of an otherwise real box.
const positions=stock.geometry.attributes.position.array.slice();stock.geometry.attributes.position.array.fill(Infinity);
assert.equal(censusEquipment(root).invalidWeaponMarkers,1,'nonfinite triangle area cannot validate stock');
stock.geometry.attributes.position.array.set(positions);stock.geometry.attributes.position.array[0]=validPosition;
stock.matrixAutoUpdate=false;stock.updateMatrix();stock.matrix.elements[0]=NaN;
assert.equal(censusEquipment(root).invalidWeaponMarkers,1,'nonfinite world transforms cannot validate stock');
stock.matrixAutoUpdate=true;stock.updateMatrix();
fitting.remove(stock);
const nested=new THREE.Group();nested.userData={fittingRoot:true,fitting:'pintleMG'};nested.add(stock);fitting.add(nested);
assert.equal(censusEquipment(root).mg,1);assert.equal(censusEquipment(root).invalidWeaponMarkers,1,'nested gun cannot legitimize empty outer marker');
root.remove(fitting);
const census=censusEquipment(root);
assert.equal(verdict(census,config(0),true).passed,true,'approved source with no roof gun needs none');
assert.equal(verdict(census,config(0),false).passed,false,'missing or changed source cannot waive weapon requirement');
assert.equal(verdict(census,undefined).passed,false,'unknown configuration keeps existing requirement');
for(const bad of [null,{}, {mg:0}, {mg:-1,invalidWeaponMarkers:0}, {mg:0,invalidWeaponMarkers:1}])assert.equal(verdict(bad,config(0),true).passed,false);
for(const count of [-1,NaN,undefined,.5])assert.equal(verdict(census,config(count),true).passed,false);
assert.equal(roofEquipmentVerdict('other_x',census,config(0),receipt).passed,false,'wrong ID cannot reuse source authorization');
for(const wrong of [{...receipt,path:'wrong.glb'},{...receipt,sha256:'b'.repeat(64)},{...receipt,verified:false}])assert.equal(roofEquipmentVerdict(id,census,config(0),wrong).passed,false,'wrong hash/path cannot reuse authorization');
stock.geometry.dispose();stock.material.dispose();
console.log('source-equipment-policy: approved actual equipment, unchanged default, and false-marker negatives pass');

const barak=BARAK_SOURCE_CONFIGURATION,barakReceipt={id:barak.id,...barak.source,verified:true};
assert.equal(roofEquipmentVerdict(barak.id,{mg:1,invalidWeaponMarkers:0},barak,barakReceipt).passed,true);
assert.equal(roofEquipmentVerdict(barak.id,{mg:0,invalidWeaponMarkers:0},barak,barakReceipt).passed,false,'Barak retains its actual source roof gun');
assert.equal(roofEquipmentVerdict(barak.id,{mg:2,invalidWeaponMarkers:0},barak,barakReceipt).passed,false,'Barak does not inherit an extra donor gun');
