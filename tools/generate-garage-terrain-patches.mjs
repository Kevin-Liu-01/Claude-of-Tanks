// Bake compact Garage terrain excerpts from the exact battlefield heightfields.
// Runtime Garage code consumes only the resulting centimeter samples; it never
// imports or constructs a battlefield terrain service.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { getMapConfig } from '../src/world/maps/index.ts';
import { createHeightField } from '../src/world/terrain.ts';

const MAP_IDS = [
  'verdant', 'desert', 'winter', 'urban', 'coastal',
  'railyard', 'monsoon', 'alpine', 'badlands', 'foundry',
];
const WIDTH = 41;
const HEIGHT = 37;
const SIZE_X_M = 96;
const SIZE_Z_M = 84;
const TERRAIN_SEED = 1337;
const outputUrl = new URL('../src/ui/garageTerrainPatches.generated.ts', import.meta.url);

function smoothstep(edge0, edge1, value) {
  const t = Math.max(0, Math.min(1, (value - edge0) / (edge1 - edge0)));
  return t * t * (3 - 2 * t);
}

function encodeInt16(values) {
  const bytes = new Uint8Array(values.length * 2);
  const view = new DataView(bytes.buffer);
  values.forEach((value, index) => view.setInt16(index * 2, value, true));
  return Buffer.from(bytes).toString('base64');
}

const records = [];
for (const mapId of MAP_IDS) {
  const config = getMapConfig(mapId);
  const field = createHeightField(TERRAIN_SEED, config);
  const anchor = config.spawns.player;
  const anchorY = field.getHeightAt(anchor.x, anchor.z);
  const values = [];
  let min = Infinity;
  let max = -Infinity;
  for (let row = 0; row < HEIGHT; row += 1) {
    const localZ = -SIZE_Z_M / 2 + (row / (HEIGHT - 1)) * SIZE_Z_M;
    for (let column = 0; column < WIDTH; column += 1) {
      const localX = -SIZE_X_M / 2 + (column / (WIDTH - 1)) * SIZE_X_M;
      const sourceY = field.getHeightAt(anchor.x + localX, anchor.z + localZ) - anchorY;
      // The authored spawn pad already suppresses severe relief. This final
      // service-apron feather guarantees the hero tank and turntable remain
      // level while preserving the real terrain outside the immediate bay.
      const keep = smoothstep(10, 19, Math.hypot(localX, localZ));
      const heightM = sourceY * keep;
      const centimeters = Math.max(-32767, Math.min(32767, Math.round(heightM * 100)));
      values.push(centimeters);
      min = Math.min(min, centimeters / 100);
      max = Math.max(max, centimeters / 100);
    }
  }
  records.push({ mapId, anchor, min, max, encoded: encodeInt16(values) });
}

const source = `// GENERATED by tools/generate-garage-terrain-patches.mjs. Do not edit.\n\n`
  + `export interface GarageTerrainPatch {\n`
  + `  readonly mapId: string;\n  readonly width: number;\n  readonly height: number;\n`
  + `  readonly sizeXM: number;\n  readonly sizeZM: number;\n`
  + `  readonly sourceAnchor: readonly [number, number];\n`
  + `  readonly minM: number;\n  readonly maxM: number;\n  readonly centimetersBase64: string;\n}\n\n`
  + `const PATCHES = Object.freeze<Record<string, GarageTerrainPatch>>({\n`
  + records.map((record) => `  ${record.mapId}: Object.freeze({ mapId: '${record.mapId}', width: ${WIDTH}, height: ${HEIGHT}, sizeXM: ${SIZE_X_M}, sizeZM: ${SIZE_Z_M}, sourceAnchor: [${record.anchor.x}, ${record.anchor.z}] as const, minM: ${record.min.toFixed(2)}, maxM: ${record.max.toFixed(2)}, centimetersBase64: '${record.encoded}' }),`).join('\n')
  + `\n});\n\n`
  + `export function getGarageTerrainPatch(mapId: string): GarageTerrainPatch {\n`
  + `  return PATCHES[mapId] || PATCHES.verdant;\n}\n`;

const outputPath = fileURLToPath(outputUrl);
if (process.argv.includes('--check')) {
  const existing = await readFile(outputPath, 'utf8');
  if (existing !== source) {
    throw new Error('Garage terrain excerpts are stale; run npm run garage:terrain:update');
  }
  console.log(`garage terrain excerpts: current (${records.length} battlefield excerpts)`);
} else {
  await writeFile(outputPath, source);
  console.log(`wrote ${outputPath} (${records.length} battlefield excerpts)`);
}
