import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { sourceAfterInteriorFillValidation, validateInteriorFillModule } from './native-interior-fill-policy.mjs';

const encode = spans => {
  const data = Buffer.alloc(spans.length * 2);
  spans.forEach((value, index) => data.writeUInt16LE(value, index * 2));
  return data.toString('base64');
};
const moduleFor = value => `// Generated by tools/gen-interior-fills.mjs. Do not hand-edit.
import type { InteriorFillRecord } from '../interiorFills.ts';
export const INTERIOR_FILLS: Readonly<Record<string, InteriorFillRecord>> = Object.freeze({
  "fixture": { v: .025, o: [0, 0, -2], t: [0, 1, 0], hull: "${value}" },
});`;
const valid = moduleFor(encode([0, 1, 2, 3, 4, 5]));
const path = 'src/vehicles/interiorFillGroups/fixture.generated.ts';
assert.deepEqual(validateInteriorFillModule(valid), { vehicleCount: 1, componentCount: 1 });
assert.equal(sourceAfterInteriorFillValidation(path, valid), '');
assert.equal(sourceAfterInteriorFillValidation('src/vehicles/profiles/fixture.ts', valid), valid,
  'a profile cannot use the generated-data exception');
for (const invalid of [
  valid.replace('hull:', 'vertices:'),
  valid.replace('"fixture":', '"__proto__":'),
  valid.replace('o: [0, 0, -2]', 'o: [64, 0, -2]'),
  valid.replace('v: .025', 'v: getSize()'),
  valid.replace('t: [0, 1, 0]', 't: [0, Infinity, 0]'),
  valid.replace('v: .025', 'v: -1'),
  valid.replace('v: .025', 'v: .025, v: .05'),
  valid.replace('Object.freeze', 'loadExternalMesh'),
  valid + '\nrunCode();',
  moduleFor('AAAA'), // one Uint16 is not a box
  moduleFor(encode([9, 1, 2, 3, 4, 5])), // inverted span
  moduleFor(encode([0, 1, 2, 65535, 4, 5])), // impossible vehicle grid
  valid.replace('Do not hand-edit.', 'Unverified payload.'),
]) assert.throws(() => sourceAfterInteriorFillValidation(path, invalid));

const reader = readFileSync(new URL('../src/vehicles/interiorFills.ts', import.meta.url), 'utf8');
const checkedReader = sourceAfterInteriorFillValidation('src/vehicles/interiorFills.ts', reader);
assert.ok(!/\batob\s*\(/.test(checkedReader), 'only the reviewed span decoder is removed');
const injected = sourceAfterInteriorFillValidation('src/vehicles/interiorFills.ts', reader + '\natob(arbitraryMesh);');
assert.match(injected, /atob\(arbitraryMesh\)/, 'an extra decoder remains visible to the generic audit');
assert.throws(() => sourceAfterInteriorFillValidation('src/vehicles/interiorFills.ts', reader.replace('const binary = atob(encoded);', 'const binary = atob(externalVertices);')));

let count = 0;
const directory = new URL('../src/vehicles/interiorFillGroups/', import.meta.url);
for (const file of readdirSync(directory).filter(file => file.endsWith('.generated.ts'))) {
  validateInteriorFillModule(readFileSync(new URL(file, directory), 'utf8'));
  count++;
}
console.log(`native-interior-fill-policy: ${count} generated groups; malformed spans, executable payloads and decoder substitution rejected`);
