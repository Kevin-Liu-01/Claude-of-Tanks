#!/usr/bin/env node
// riding-parts-manifest.mjs — every riding cradle and riding station option set each tank's build asks for (UI-LOCKDOWN E,
// 2026-10-25). Copyright (c) 2026 Kevin B. Liu. First-party tool; see NOTICE.md.
//
// Builds the roster at HIGH and LOW, watching the two stores in src/vehicles/ridingPartsCache.ts, and writes the keys each
// tank reads to src/vehicles/ridingPartsManifest.generated.ts, which only the riding-parts worker imports: the prebuild
// (vehicles/ridingPartsPrebuild.ts) asks the worker for a tank's keys before that tank is built. A stale manifest costs only
// a prefetch, never a build: a key the worker has not seeded is built in-line, as before.
//
//   node tools/riding-parts-manifest.mjs            write the manifest
//   node tools/riding-parts-manifest.mjs --check    exit 1 when the manifest differs from the fleet as it builds now
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const OUT = fileURLToPath(new URL('../src/vehicles/ridingPartsManifest.generated.ts', import.meta.url));
await import('../src/vehicles/tankFactory.ts');
const { createTank } = await import('../src/vehicles/tankFactoryCore.ts');
const { RIDING_CRADLE_PARTS, RIDING_STATION_PARTS } = await import('../src/vehicles/ridingPartsCache.ts');
const { fleetRoster, ledgerBuildOptions } = await import('./fleet-geometry-digest.mjs');

let reads = new Set();
for (const store of [RIDING_CRADLE_PARTS, RIDING_STATION_PARTS]) {
  const get = store.get.bind(store);
  store.get = (key) => { reads.add(key); return get(key); };
}
const keys = [], index = new Map(), bySpec = {};
for (const id of fleetRoster()) {
  reads = new Set();
  for (const quality of ['high', 'low']) createTank(id, null, ledgerBuildOptions(quality)).dispose();
  const own = [...reads].filter((key) => RIDING_CRADLE_PARTS.has(key) || RIDING_STATION_PARTS.has(key)).sort();
  if (!own.length) continue;
  bySpec[id] = own.map((key) => {
    if (!index.has(key)) { index.set(key, keys.length); keys.push(key); }
    return index.get(key);
  });
}
const text = `// Generated by tools/riding-parts-manifest.mjs: do not edit. Every riding cradle and riding station option set each tank's
// build reads (src/vehicles/ridingPartsCache.ts keys), at HIGH and LOW. Only the riding-parts worker imports it.
export const RIDING_PARTS_KEYS: readonly string[] = ${JSON.stringify(keys, null, 1)};
/** Each tank's keys, as indexes into RIDING_PARTS_KEYS. */
export const RIDING_PARTS_BY_SPEC: Readonly<Record<string, readonly number[]>> = ${JSON.stringify(bySpec)};
`;
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch { /* none yet */ }
  if (current !== text) { console.error('riding-parts-manifest: stale (node tools/riding-parts-manifest.mjs)'); process.exit(1); }
  console.log(`riding-parts-manifest: ${keys.length} option sets for ${Object.keys(bySpec).length} tanks, current`);
} else {
  writeFileSync(OUT, text);
  console.log(`riding-parts-manifest: ${keys.length} option sets for ${Object.keys(bySpec).length} tanks -> ${OUT}`);
}
