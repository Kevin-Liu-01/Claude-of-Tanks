// mission-dock-seats.mjs — the boot-side projection of the drone dock's seat records (2026-10-12, the 221 integration).
// The decor builder's dock keep-out (src/vehicles/decorations.ts dockKeepOut, items 2b/2c) needs each seat's frame,
// datum and cradle footprint while it builds a tank, so it runs in every page that builds one (the garage boot, the
// gallery). src/sim/missionAttachmentSeats.generated.ts also carries each record's audit signature and 64-hex geometry
// hash (about half its gzip bytes, read only by the generator's --check); src/sim/missionDockSeats.generated.ts is the
// same records without those two keys, written beside it by tools/gen-mission-attachment-seats.mjs and held to it by
// src/sim/missionDockSeats.selftest.mjs.
//
//   node tools/mission-dock-seats.mjs           rewrite src/sim/missionDockSeats.generated.ts from the seat records
//   node tools/mission-dock-seats.mjs --check   exit 1 when it differs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const MISSION_DOCK_SEATS_PATH = 'src/sim/missionDockSeats.generated.ts';
const AUDIT_KEYS = new Set(['signature', 'geometryHash']);

/** The projection's source text for a full seat table (id -> native record), ids in the generator's order. */
export function missionDockSeatsSource(records) {
  const rows = Object.entries(records).sort(([a], [b]) => a.localeCompare(b)).map(([id, record]) =>
    '  ' + JSON.stringify(id) + ': ' + JSON.stringify(Object.fromEntries(Object.entries(record).filter(([key]) => !AUDIT_KEYS.has(key)))));
  return '// Generated by tools/gen-mission-attachment-seats.mjs (tools/mission-dock-seats.mjs). Do not hand-edit.\n'
    + '// The seat records of missionAttachmentSeats.generated.ts without their audit signature and geometry hash.\n'
    + "import type { MissionAttachment } from './missionAttachment.ts';\n"
    + `export const MISSION_DOCK_SEATS: Readonly<Record<string,MissionAttachment>> = {\n${rows.join(',\n')}\n};\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const { MISSION_ATTACHMENT_SEATS } = await import(pathToFileURL(path.join(root, 'src/sim/missionAttachmentSeats.generated.ts')).href);
  const want = missionDockSeatsSource(MISSION_ATTACHMENT_SEATS), file = path.join(root, MISSION_DOCK_SEATS_PATH);
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    if (current !== want) { console.error(`${MISSION_DOCK_SEATS_PATH} is stale: run node tools/mission-dock-seats.mjs`); process.exit(1); }
    console.log(`${MISSION_DOCK_SEATS_PATH}: current (${Object.keys(MISSION_ATTACHMENT_SEATS).length} seats)`);
  } else {
    fs.writeFileSync(file, want);
    console.log(`${MISSION_DOCK_SEATS_PATH}: wrote ${Object.keys(MISSION_ATTACHMENT_SEATS).length} seats`);
  }
}
