// Generate exact runtime paint seats from the authoritative surface solver.
// First-party procedural vehicle artwork and engineering: Kevin Liu.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createTank } from '../src/vehicles/tankFactory.js';
import { ALL_TANK_IDS } from '../src/vehicles/specs.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(root, 'src/vehicles/vehicleMarkingSeats.generated.js');
const check = process.argv.includes('--check');
const round = (value) => Number(Number(value).toFixed(7));
const vector = (values) => values.map(round);
const records = {};

for (const id of ALL_TANK_IDS) {
  const visual = createTank(id, null, { proceduralOnly: true, geometryReceipt: true });
  const seats = [];
  visual.root.traverse((object) => {
    if (!object.userData?.vehicleMarking) return;
    const kind = object.userData.markingKind;
    if (kind !== 'insignia' && kind !== 'designation') return;
    seats.push({
      kind,
      parent: object.userData.surfaceOwner,
      size: round(object.scale.x),
      pos: vector(object.position.toArray()),
      quaternion: vector(object.quaternion.toArray()),
      surfaceMesh: object.userData.surfaceMesh,
      anchorProfile: object.userData.markingAnchorProfile,
      visibilitySamples: object.userData.visibilitySamples,
      visibilityClearSamples: object.userData.visibilityClearSamples,
      visibilityRatio: round(object.userData.visibilityRatio),
      maximumSurfaceErrorM: round(object.userData.maximumSurfaceErrorM),
    });
  });
  records[id] = { schemaVersion: 1, seats };
  visual.dispose();
  process.stdout.write(`\r[marking-seats] ${Object.keys(records).length}/${ALL_TANK_IDS.length} ${id.padEnd(24)}`);
}

const source = `// Generated by tools/gen-vehicle-marking-seats.mjs.\n`
  + `// First-party procedural vehicle artwork and engineering: Kevin Liu.\n\n`
  + `export const VEHICLE_MARKING_SEAT_SCHEMA_VERSION = 1;\n\n`
  + `export const VEHICLE_MARKING_SEATS = Object.freeze(${JSON.stringify(records, null, 2)});\n`;
const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
process.stdout.write('\n');
if (check) {
  if (current !== source) {
    console.error('[marking-seats] generated receipts are stale; run npm run tank:marking-seats:update');
    process.exit(1);
  }
  console.log(`[marking-seats] ${ALL_TANK_IDS.length} receipts current`);
} else {
  fs.writeFileSync(outputPath, source);
  console.log(`[marking-seats] wrote ${path.relative(root, outputPath)}`);
}
