// Generate exact runtime paint seats from the authoritative surface solver.
// First-party procedural vehicle artwork and engineering: Kevin Liu.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createTank } from '../src/vehicles/tankFactory.ts';
import { ALL_TANK_IDS } from '../src/vehicles/specs.ts';
import { FLEET_GROUP_BY_ID } from '../src/vehicles/fleetManifest.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(root, 'src/vehicles/vehicleMarkingSeats.generated.ts');
const groupOutputDir = path.join(root, 'src/vehicles/vehicleMarkingSeatGroups');
const loaderOutputPath = path.join(root, 'src/vehicles/vehicleMarkingSeatLoaders.generated.ts');
const check = process.argv.includes('--check');
const round = (value) => Number(Number(value).toFixed(7));
const vector = (values) => values.map(round);
const records = {};

for (const id of ALL_TANK_IDS) {
  const visual = createTank(id, null, { proceduralOnly: true, geometryReceipt: true });
  const seats = [];
  visual.root.traverse((object) => {
    if (!object.userData?.vehicleMarking) return;
    const kind = object.userData.markingKind;
    if (kind !== 'insignia' && kind !== 'designation') return;
    seats.push({
      kind,
      parent: object.userData.surfaceOwner,
      size: round(object.scale.x),
      pos: vector(object.position.toArray()),
      quaternion: vector(object.quaternion.toArray()),
      surfaceMesh: object.userData.surfaceMesh,
      anchorProfile: object.userData.markingAnchorProfile,
      visibilitySamples: object.userData.visibilitySamples,
      visibilityClearSamples: object.userData.visibilityClearSamples,
      visibilityRatio: round(object.userData.visibilityRatio),
      maximumSurfaceErrorM: round(object.userData.maximumSurfaceErrorM),
    });
  });
  records[id] = { schemaVersion: 1, seats };
  visual.dispose();
  process.stdout.write(`\r[marking-seats] ${Object.keys(records).length}/${ALL_TANK_IDS.length} ${id.padEnd(24)}`);
}

const fileHeader = `// Generated by tools/gen-vehicle-marking-seats.mjs.\n`
  + `// First-party procedural vehicle artwork and engineering: Kevin Liu.\n\n`;
const sourceHeader = fileHeader
  + `export const VEHICLE_MARKING_SEAT_SCHEMA_VERSION = 1;\n\n`;

const recordsByGroup = {};
for (const [id, record] of Object.entries(records)) {
  const group = FLEET_GROUP_BY_ID[id] || 'core';
  (recordsByGroup[group] ||= {})[id] = record;
}
const groupNames = Object.keys(recordsByGroup).sort();
const groupBinding = (group) => `SEATS_${group.replace(/[^A-Za-z0-9]/g, '_').toUpperCase()}`;
const groupSources = Object.fromEntries(groupNames.map((group) => [
  path.join(groupOutputDir, `${group}.generated.ts`),
  sourceHeader
    + `import type { VehicleMarkingSeatRecord } from '../vehicleMarkingSeatRegistry.ts';\n\n`
    + `export const VEHICLE_MARKING_SEATS: Readonly<Record<string, VehicleMarkingSeatRecord>> = Object.freeze(${JSON.stringify(recordsByGroup[group], null, 2)});\n`,
]));
const source = fileHeader
  + `import type { VehicleMarkingSeatRecord } from './vehicleMarkingSeatRegistry.ts';\n`
  + groupNames.map((group) => `import { VEHICLE_MARKING_SEATS as ${groupBinding(group)} } from './vehicleMarkingSeatGroups/${group}.generated.ts';`).join('\n')
  + `\n\nexport const VEHICLE_MARKING_SEAT_SCHEMA_VERSION = 1;\n\n`
  + `export const VEHICLE_MARKING_SEATS: Readonly<Record<string, VehicleMarkingSeatRecord>> = Object.freeze(Object.assign({},\n`
  + groupNames.map((group) => `  ${groupBinding(group)},`).join('\n')
  + `\n));\n`;
const loaderSource = `// Generated by tools/gen-vehicle-marking-seats.mjs.\n`
  + `// Dynamic imports stay explicit so Vite emits one immutable receipt chunk per visual family.\n\n`
  + `import type { VehicleMarkingSeatRecord } from './vehicleMarkingSeatRegistry.ts';\n\n`
  + `type MarkingSeatGroupModule = { VEHICLE_MARKING_SEATS: Readonly<Record<string, VehicleMarkingSeatRecord>> };\n\n`
  + `export const VEHICLE_MARKING_SEAT_GROUP_LOADERS: Readonly<Record<string, () => Promise<MarkingSeatGroupModule>>> = Object.freeze({\n`
  + groupNames.map((group) => `  ${JSON.stringify(group)}: () => import('./vehicleMarkingSeatGroups/${group}.generated.ts'),`).join('\n')
  + `\n});\n`;

const outputs = {
  [outputPath]: source,
  [loaderOutputPath]: loaderSource,
  ...groupSources,
};
const staleGroupPaths = fs.existsSync(groupOutputDir)
  ? fs.readdirSync(groupOutputDir)
    .filter((name) => name.endsWith('.generated.js') || name.endsWith('.generated.ts'))
    .map((name) => path.join(groupOutputDir, name))
    .filter((filePath) => !(filePath in outputs))
  : [];
process.stdout.write('\n');
if (check) {
  const staleOutputs = Object.entries(outputs)
    .filter(([filePath, expected]) => !fs.existsSync(filePath) || fs.readFileSync(filePath, 'utf8') !== expected)
    .map(([filePath]) => path.relative(root, filePath));
  if (staleOutputs.length || staleGroupPaths.length) {
    console.error('[marking-seats] generated receipts are stale; run npm run tank:marking-seats:update');
    for (const filePath of [...staleOutputs, ...staleGroupPaths.map((item) => path.relative(root, item))]) {
      console.error(`  ${filePath}`);
    }
    process.exit(1);
  }
  console.log(`[marking-seats] ${ALL_TANK_IDS.length} receipts across ${groupNames.length} demand groups current`);
} else {
  fs.mkdirSync(groupOutputDir, { recursive: true });
  for (const [filePath, contents] of Object.entries(outputs)) fs.writeFileSync(filePath, contents);
  for (const filePath of staleGroupPaths) fs.unlinkSync(filePath);
  console.log(`[marking-seats] wrote ${ALL_TANK_IDS.length} receipts across ${groupNames.length} demand groups`);
}
