import assert from 'node:assert/strict';
import * as THREE from 'three';
import {measureSlabBounds,triangleSlabPoints} from './section-slab-bounds.mjs';
const root=new THREE.Group();
const flank=new THREE.Mesh(new THREE.BoxGeometry(3.55,2,8),new THREE.MeshBasicMaterial());
flank.name='parallel-flank';flank.position.y=1;root.add(flank);
let [row]=measureSlabBounds(root,[[-.2,.2]]);
assert.ok(Math.abs(row.width-3.55)<1e-6);
assert.equal(row.top,2);assert.equal(row.bottom,0);
assert.equal(row.witness.xMax,'parallel-flank');
assert.equal(measureSlabBounds(root,[[5,6]])[0].empty,true);
flank.visible=false;
assert.equal(measureSlabBounds(root,[[-.2,.2]])[0].empty,true);
flank.visible=true;
assert.equal(measureSlabBounds(root,[[-.2,.2]],()=>false)[0].empty,true);
flank.position.y+=.1;
assert.ok(Math.abs(measureSlabBounds(root,[[-.2,.2]])[0].top-2.1)<1e-9);
flank.geometry.dispose();flank.material.dispose();root.remove(flank);
const copies=new THREE.InstancedMesh(new THREE.BoxGeometry(.3,.4,.5),new THREE.MeshBasicMaterial(),2);
copies.setMatrixAt(0,new THREE.Matrix4().makeTranslation(-2,1,0));
copies.setMatrixAt(1,new THREE.Matrix4().makeTranslation(2,1,0));root.add(copies);
row=measureSlabBounds(root,[[-.1,.1]])[0];
assert.ok(Math.abs(row.width-4.3)<1e-6);assert.ok(Math.abs(row.top-1.2)<1e-6);
const tri=[[-2,0,-2],[2,0,2],[0,2,2]].map(p=>new THREE.Vector3(...p));
const points=triangleSlabPoints(tri,-.5,.5);
assert.equal(points.length,4);
assert.ok(points.every(p=>p.z>=-.5 && p.z<=.5));
assert.throws(()=>triangleSlabPoints(tri,0,0),/Invalid slab/);
copies.geometry.dispose();copies.material.dispose();
console.log('section-slab-bounds.selftest: parallel surfaces, empty space, transforms, instances and displacement retained');
