export const MANUAL_SUITE_NAMES = Object.freeze(Object.keys(MANUAL_SUITES));
const SUITE_OF = new Map(Object.entries(MANUAL_SUITES).flatMap(([name, entry]) => entry.files.map((file) => [file, name])));

/** The manual suite a registered receipt belongs to, or null for the default tier. */
export function manualSuiteOf(file) {
  return SUITE_OF.get(file) ?? null;
}

/** The default tier of a registry selection, in its order. */
export function defaultTierFiles(files) {
  return files.filter((file) => !SUITE_OF.has(file));
}

/** `--heavy=` names: a comma list of suites or `all`; an unknown name throws. */
export function parseSuiteNames(value) {
  const names = value.split(',').map((name) => name.trim()).filter(Boolean);
  if (!names.length) throw new Error('--heavy needs a suite name: ' + MANUAL_SUITE_NAMES.join(', ') + ', or all');
  if (names.includes('all')) return [...MANUAL_SUITE_NAMES];
  for (const name of names) {
    if (!MANUAL_SUITES[name]) throw new Error(`unknown manual suite "${name}". Expected: ${MANUAL_SUITE_NAMES.join(', ')}, or all`);
  }
  return [...new Set(names)];
}

/** The registered receipts of the named suites, in registry order. */
export function manualSuiteFiles(files, names) {
  const wanted = new Set(names);
  return files.filter((file) => wanted.has(SUITE_OF.get(file)));
}

/** Tank ids a receipt's source names as string literals (the same token rule the audit and lane mode use). */
export function namedIds(text, ids) {
  const found = new Set();
  for (const match of text.matchAll(/['"`]([a-z0-9_]+)['"`]/g)) if (ids.has(match[1])) found.add(match[1]);
  return found;
}
