// Generate boot-safe metadata modules from the two legacy files that still
// combine roster specs with large Three.js builder implementations.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

await import('../src/vehicles/modern1.js');
await import('../src/vehicles/modern2.js');
const { TANK_SPECS } = await import('../src/vehicles/specs.js');

const check = process.argv.includes('--check');
const waves = [
  {
    name: 'modern1',
    ids: ['t72b3', 'merkava4', 'leo2a6'],
    delisted: ['t72b3', 'merkava4'],
  },
  {
    name: 'modern2',
    ids: [
      'leo2a4', 't80u', 'leclerc', 'leclerc_xlr', 'amx56',
      'type99a', 'leo1a5', 'mbt70', 't14',
    ],
    delisted: [],
  },
];

function assertSerializable(value, path = 'spec') {
  if (value === undefined || typeof value === 'function' || typeof value === 'symbol') {
    throw new TypeError(`${path} contains non-serializable ${typeof value}`);
  }
  if (typeof value === 'number' && !Number.isFinite(value)) {
    throw new TypeError(`${path} contains a non-finite number`);
  }
  if (!value || typeof value !== 'object') return;
  if (Array.isArray(value)) {
    value.forEach((entry, index) => assertSerializable(entry, `${path}[${index}]`));
    return;
  }
  for (const [key, entry] of Object.entries(value)) assertSerializable(entry, `${path}.${key}`);
}

function moduleSource({ name, ids, delisted }) {
  const specs = Object.fromEntries(ids.map((id) => {
    const spec = TANK_SPECS[id];
    if (!spec) throw new Error(`Missing ${name} spec ${id}`);
    assertSerializable(spec, id);
    return [id, spec];
  }));
  const json = JSON.stringify(specs);
  return `// Generated by tools/gen-legacy-fleet-specs.mjs. Do not hand-edit.\n`
    + `// Spec metadata only; authored Three.js builders remain demand-loaded.\n\n`
    + `import { ALL_TANK_IDS, MODEL_SOURCE, TANK_SPECS } from './specs.js';\n\n`
    + `import { bindFleetRegistries } from './fleetSpecRegistry.ts';\n`
    + `import type { FleetTankSpec } from './specContracts.ts';\n\n`
    + `const SPECS: Readonly<Record<string, FleetTankSpec>> = JSON.parse(${JSON.stringify(json)});\n`
    + `const DELISTED: ReadonlySet<string> = new Set(${JSON.stringify(delisted)});\n`
    + `const registries = bindFleetRegistries(TANK_SPECS, MODEL_SOURCE, ALL_TANK_IDS);\n\n`
    + `for (const [id, spec] of Object.entries(SPECS)) {\n`
    + `  registries.tankSpecs[id] ||= spec;\n`
    + `  registries.modelSources[id] ||= { source: 'procedural' };\n`
    + `  if (!DELISTED.has(id) && !registries.allTankIds.includes(id)) registries.allTankIds.push(id);\n`
    + `}\n`;
}

let stale = false;
for (const wave of waves) {
  const outPath = resolve(`src/vehicles/${wave.name}Specs.generated.ts`);
  const source = moduleSource(wave);
  if (check) {
    if (!existsSync(outPath) || readFileSync(outPath, 'utf8') !== source) {
      console.error(`[fleet-specs] stale ${outPath}`);
      stale = true;
    }
  } else {
    writeFileSync(outPath, source);
    console.log(`[fleet-specs] wrote ${wave.ids.length} specs -> ${outPath}`);
  }
}

if (stale) process.exit(2);
if (check) console.log('[fleet-specs] PASS — legacy metadata matches authored sources');
