#!/usr/bin/env node
// TEAM NATIONS (gameplay-modes-228): writes src/sim/nationIndex.generated.ts, the light [id, country, era, tier] table of
// every production bot vehicle that the rooms Worker, the LAN service and the p2p host plan multiplayer bot seats from
// (they cannot load the fleet; the Worker's program may not reach src/vehicles at all: roomWorkerProgram.selftest).
// `--check` fails when the committed table differs from the fleet (run it with the tank-addition procedure; regenerate
// with `node tools/nation-index.mjs` only when fleet ids, nations, eras or tiers change).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ensureFullFleet } from '../src/vehicles/fleetFactory.ts';
import { getSpec, PRODUCTION_TANK_IDS } from '../src/vehicles/specs.ts';
import { isBotTankId } from '../src/game/matchmaking.ts';
import { tankTier } from '../src/vehicles/tier.ts';
import { countryOfVehicle } from '../src/sim/countries.ts';

await ensureFullFleet();
const target = fileURLToPath(new URL('../src/sim/nationIndex.generated.ts', import.meta.url));
const rows = PRODUCTION_TANK_IDS.filter((id) => isBotTankId(id) && getSpec(id) && !getSpec(id).aerial && getSpec(id).gun?.shells?.length)
  .map((id) => [id, countryOfVehicle(id, getSpec(id).nation), getSpec(id).era ?? null, tankTier(id)]);
const body = rows.map((row) => `  ${JSON.stringify(row)},`).join('\n');
const source = `// Generated by tools/nation-index.mjs (TEAM NATIONS, gameplay-modes-228): every production bot vehicle as
// [id, country, era, tier] for the multiplayer bot planner (src/mp/room/roomBots.ts). Do not edit by hand:
// \`node tools/nation-index.mjs\` regenerates it, \`node tools/nation-index.mjs --check\` (nationIndex.selftest) compares.
import type { CountryId } from './countries.ts';

export const NATION_INDEX: readonly (readonly [string, CountryId | null, string | null, number])[] = [
${body}
];
`;
if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== source) {
    console.error(`nation-index: src/sim/nationIndex.generated.ts is stale against the fleet (${rows.length} production bot vehicles); run node tools/nation-index.mjs`);
    process.exit(1);
  }
  console.log(`nation-index: ${rows.length} production bot vehicles, the committed index matches the fleet`);
} else {
  writeFileSync(target, source);
  console.log(`nation-index: wrote ${rows.length} rows to src/sim/nationIndex.generated.ts (${Buffer.byteLength(source)} bytes)`);
}
process.exit(0);
