// The combat anatomy generator's rows and files (tools/gen-combat-anatomy.mjs), apart from the fleet it measures: the
// row each id takes in a run (measured, kept, re-seated or a part's) and the files those rows serialize to. Pure, so the
// parts receipt (tools/combat-anatomy-parts.selftest.mjs) runs them on a fixture roster. First-party tooling: Kevin B. Liu.
import { join } from 'node:path';

/**
 * Each id's row in a run, in roster order (the files' bytes follow it):
 *   only     the ids this run measures (null: every id); any other id keeps its committed row, or is measured when it
 *            has none
 *   part     one part of a parallel run (tools/changed-only/parts.mjs): exactly `only`, and no other row
 *   parts    a merge: the rows the parts measured, by id, taken in place of measuring them; a part's row for an id this
 *            run does not measure throws
 *   measure  (id) => row; reseat (id) => row (--crew-only)
 */
export function anatomyRows({ roster, only = null, committed = {}, part = false, parts = null, measure, reseat = null }) {
  if (part && !only) throw new Error('[combat-anatomy] a part measures --ids');
  for (const id of only ?? []) if (!roster.includes(id)) throw new Error(`[combat-anatomy] unknown id ${id}`);
  const rows = {}, taken = new Set();
  for (const id of roster) {
    if (part && !only.has(id)) continue;
    if (only && !only.has(id) && committed[id]) { rows[id] = committed[id]; continue; }
    if (reseat) { rows[id] = reseat(id); continue; }
    if (parts?.has(id)) { rows[id] = parts.get(id); taken.add(id); continue; }
    rows[id] = measure(id);
  }
  const stray = [...(parts?.keys() ?? [])].filter((id) => !taken.has(id));
  if (stray.length) throw new Error(`[combat-anatomy] --merge-from rows for ids this run does not measure: ${stray.join(', ')}`);
  return rows;
}

const fileHeader = `// Generated by tools/gen-combat-anatomy.mjs. Do not hand-edit.\n`
  + `// Main armor and internal volumes are calibrated to these first-party geometry receipts.\n`;
const groupBinding = (group) => `CALIBRATIONS_${group.replace(/[^A-Za-z0-9]/g, '_').toUpperCase()}`;

/** The files a run's rows serialize to ({ path: contents }): each demand group's module, the index and the loader map. */
export function anatomyOutputFiles(rows, groupById, { outPath, groupDir, loaderPath }) {
  const rowsByGroup = {};
  for (const [id, calibration] of Object.entries(rows)) {
    const group = groupById[id] || 'core';
    (rowsByGroup[group] ||= {})[id] = calibration;
  }
  const groupNames = Object.keys(rowsByGroup).sort();
  const groupSources = Object.fromEntries(groupNames.map((group) => [
    join(groupDir, `${group}.generated.ts`),
    fileHeader
      + `import type { CombatAnatomyCalibration } from '../combatAnatomyCalibrationRegistry.ts';\n\n`
      // Collision receipts are large numeric payloads. Keep generated modules
      // compact so download/parse cost is governed by data, not indentation.
      + `export const COMBAT_ANATOMY_CALIBRATIONS: Readonly<Record<string, CombatAnatomyCalibration>> = Object.freeze(${JSON.stringify(rowsByGroup[group])});\n`,
  ]));
  const source = fileHeader
    + `import type { CombatAnatomyCalibration } from './combatAnatomyCalibrationRegistry.ts';\n`
    + groupNames.map((group) => `import { COMBAT_ANATOMY_CALIBRATIONS as ${groupBinding(group)} } from './combatAnatomyGroups/${group}.generated.ts';`).join('\n')
    + `\n\nexport const COMBAT_ANATOMY_CALIBRATIONS: Readonly<Record<string, CombatAnatomyCalibration>> = Object.freeze(Object.assign({},\n`
    + groupNames.map((group) => `  ${groupBinding(group)},`).join('\n')
    + `\n));\n`;
  const loaderSource = `// Generated by tools/gen-combat-anatomy.mjs. Do not hand-edit.\n`
    + `// Explicit imports let Vite emit one immutable calibration chunk per visual family.\n\n`
    + `import type { CombatAnatomyCalibration } from './combatAnatomyCalibrationRegistry.ts';\n\n`
    + `type CalibrationGroupModule = { COMBAT_ANATOMY_CALIBRATIONS: Readonly<Record<string, CombatAnatomyCalibration>> };\n\n`
    + `export const COMBAT_ANATOMY_GROUP_LOADERS: Readonly<Record<string, () => Promise<CalibrationGroupModule>>> = Object.freeze({\n`
    + groupNames.map((group) => `  ${JSON.stringify(group)}: () => import('./combatAnatomyGroups/${group}.generated.ts'),`).join('\n')
    + `\n});\n`;
  return { outputs: { [outPath]: source, [loaderPath]: loaderSource, ...groupSources }, groupNames };
}
