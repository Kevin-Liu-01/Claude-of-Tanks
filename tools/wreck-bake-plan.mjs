#!/usr/bin/env node
// The wreck bake plan (2026-10-07, the time-to-battle lane): per map, the wreck bakes its props build requests of the
// wreck worker, in order — recorded in Node by draining the worker-wreck build (the browser's: the async vegetation,
// its far grass deferred) with each request answered by the worker's own bake (the same donor build, pose and paint,
// through the same wire), as the browser would. The browser starts these bakes when the world build starts, beside the
// terrain and vegetation (src/world/wreckBakePrefetch.ts); a request the plan does not hold is baked where it is asked,
// so a stale plan costs time, never a different wreck.
//
// Every map is recorded on the desktop and the phone tier (a child process each: the tier is resolved once per
// process), on the standard terrain and the assault variant's trenches; the plan keeps the desktop rows of every map and
// a variant's rows only where they differ from what it falls back to (wreckBakePrefetch.ts resolveWreckBakeRows). A bake
// is the same for the same donor, seed and pop, so each child bakes it once.
//
//   node tools/wreck-bake-plan.mjs [--maps=all|<id,...>] [--workers=4] --write   records, and rewrites the plan (a partial
//                                                                                 run keeps the other maps' rows)
//   node tools/wreck-bake-plan.mjs [--maps=...] [--workers=4] --check            fails when the committed plan differs
//                                                                                 (src/world/wreckBakePlanDrift.selftest.mjs)
//   node tools/wreck-bake-plan.mjs --record --tier=desktop|mobile --maps=<ids>   one child: a PLAN line per map and terrain
import { spawn } from 'node:child_process';
import { availableParallelism } from 'node:os';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { installWorldBuildFixture } from './headlessWorldCollision.mjs';
import { isMainModule } from './map-probe-runtime.mjs';

const PLAN_FILE = new URL('../src/world/maps/wreckBakePlan.ts', import.meta.url);
const SELF = fileURLToPath(import.meta.url);
/** The plan's keys per map: the desktop rows and the three variants. */
export const WRECK_PLAN_VARIANTS = Object.freeze(['desktop', 'mobile', 'assault', 'assault-mobile']);

const rowsText = (rows) => `[${rows.map(([specId, seed, pop]) => `['${specId}', ${seed}, ${pop ? 1 : 0}]`).join(', ')}]`;
const keyText = (key) => (/^[a-z_][a-z0-9_]*$/.test(key) ? key : `'${key}'`);
const sameRows = (a, b) => rowsText(a ?? []) === rowsText(b ?? []);

function renderWreckBakePlan({ plan, variants }) {
  const lines = [
    '// Generated by tools/wreck-bake-plan.mjs — do not edit. The wreck bakes each map\'s props build requests of the',
    '// wreck worker, in order: [donor spec, seed, ammo-rack pop]. The world build starts them beside the terrain and',
    '// vegetation (src/world/wreckBakePrefetch.ts); any other request bakes on demand.',
    'type WreckBakeRows = ReadonlyArray<readonly [string, number, 0 | 1]>;',
    '/** Every map: the desktop tier on the standard terrain. */',
    'export const WRECK_BAKE_PLAN: Readonly<Record<string, WreckBakeRows>> = {',
  ];
  for (const mapId of Object.keys(plan).sort()) lines.push(`  ${keyText(mapId)}: ${rowsText(plan[mapId])},`);
  lines.push('};',
    '/** Where a variant\'s requests differ from its fallback (resolveWreckBakeRows): <map>@mobile, @assault, @assault-mobile. */',
    'export const WRECK_BAKE_PLAN_VARIANTS: Readonly<Record<string, WreckBakeRows>> = {');
  for (const key of Object.keys(variants).sort()) lines.push(`  ${keyText(key)}: ${rowsText(variants[key])},`);
  lines.push('};', '');
  return lines.join('\n');
}

/** The rows a map resolves to for one plan key (wreckBakePrefetch.ts resolveWreckBakeRows, over plain tables). */
export function resolvePlanRows({ plan, variants }, mapId, variant) {
  const own = (v) => variants[`${mapId}@${v}`];
  const desktop = plan[mapId] ?? null;
  if (variant === 'assault-mobile') return own('assault-mobile') ?? own('mobile') ?? desktop;
  if (variant === 'assault') return own('assault') ?? desktop;
  if (variant === 'mobile') return own('mobile') ?? desktop;
  return desktop;
}

/** The plan tables from recorded rows (recorded[mapId][variant] = rows): variants only where they differ. */
export function planTables(recorded) {
  const plan = {}, variants = {};
  for (const mapId of Object.keys(recorded).sort()) {
    const r = recorded[mapId];
    plan[mapId] = r.desktop;
    for (const variant of ['mobile', 'assault', 'assault-mobile']) {
      if (!sameRows(r[variant], resolvePlanRows({ plan, variants }, mapId, variant))) variants[`${mapId}@${variant}`] = r[variant];
    }
  }
  return { plan, variants };
}

function committedTables() {
  try {
    const text = readFileSync(PLAN_FILE, 'utf8');
    const table = (name) => {
      const at = text.indexOf(`export const ${name}`);
      if (at < 0) return {};
      const body = text.slice(text.indexOf('= {', at) + 2, text.indexOf('\n};', at) + 2);
      // the generated object is JSON once its keys are quoted and its strings double-quoted
      return JSON.parse(body.replace(/^ {2}([a-z_][a-z0-9_]*):/gm, '  "$1":').replace(/^ {2}'([^']+)':/gm, '  "$1":')
        .replace(/'/g, '"').replace(/,(\s*[\]}])/g, '$1'));
    };
    return { plan: table('WRECK_BAKE_PLAN'), variants: table('WRECK_BAKE_PLAN_VARIANTS') };
  } catch (error) {
    throw new Error(`the committed plan does not parse: ${error.message}`);
  }
}

/** One child: record one tier, both terrains, for `ids`; prints a PLAN line per map and terrain. */
async function recordTier(tier, ids) {
  installWorldBuildFixture();
  if (tier === 'mobile') {
    // the phone tier, as the world receipts resolve it (quality.ts reads ?tier= once; it stays for the process)
    const saved = globalThis.window;
    globalThis.window = { location: { search: '?tier=mobile' }, localStorage: { getItem: () => null } };
    try { (await import('../src/engine/quality.ts')).resolveDeviceTier(); } finally {
      if (saved === undefined) delete globalThis.window; else globalThis.window = saved;
    }
  }
  const [mapsMod, terrain, vegetation, props, fleet, models, wrecks, wire, quality] = await Promise.all([
    import('../src/world/maps/index.ts'), import('../src/world/terrain.ts'), import('../src/world/vegetation.ts'),
    import('../src/world/props.ts'), import('../src/vehicles/fleetFactory.ts'), import('../src/world/propsModelStore.ts'),
    import('../src/world/wrecks.ts'), import('../src/world/wreckBakeWire.ts'), import('../src/engine/quality.ts'),
  ]);
  if (quality.getDeviceTier() !== tier) throw new Error(`the ${tier} child resolved the ${quality.getDeviceTier()} tier`);
  await models.preloadPropModels();
  const engine = { anisotropy: 4, setupShadowMaterial() {} };
  // the worker's own bake (src/world/wreckBakeWorker.ts): the donor's builders, the bake, the wire both ways; once per
  // donor, seed and pop (a bake is a function of those), each request handed its own unpacked copy
  const baked = new Map();
  const bake = async (specId, options) => {
    const key = `${specId}|${options.seed}|${options.pop ? 1 : 0}`;
    if (!baked.has(key)) {
      await fleet.ensureTankBuilder(specId);
      const result = wrecks.bakeTankWreck({}, specId, options);
      baked.set(key, result ? wire.packWreckBake(result).wire : null);
    }
    const packed = baked.get(key);
    return packed ? wire.unpackWreckBake(structuredClone(packed)) : null;
  };
  for (const mapId of ids) {
    for (const assault of [false, true]) {
      const t0 = Date.now();
      const base = mapsMod.getMapConfig(mapId);
      const config = assault ? { ...base, assaultTrenches: true } : base;
      const field = terrain.createHeightField(1337, config);
      const flora = await vegetation.createVegetationAsync(field, engine, 2001, config, null, false);
      const requests = await props.recordWreckBakeRequests(field, engine, 2002, config, flora, bake);
      const rows = requests.map((r) => [r.specId, r.seed, r.pop ? 1 : 0]);
      const variant = assault ? (tier === 'mobile' ? 'assault-mobile' : 'assault') : tier;
      console.log(`PLAN ${JSON.stringify({ mapId, variant, rows, ms: Date.now() - t0 })}`);
    }
  }
}

function runChild(tier, ids) {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, [SELF, '--record', `--tier=${tier}`, `--maps=${ids.join(',')}`], { stdio: ['ignore', 'pipe', 'pipe'] });
    let out = '', err = '';
    child.stdout.on('data', (chunk) => {
      out += chunk;
      for (const line of String(chunk).split('\n')) {
        if (!line.startsWith('PLAN ')) continue;
        try { const p = JSON.parse(line.slice(5)); console.error(`[wreck-bake-plan] ${p.mapId}@${p.variant}: ${p.rows.length} bake(s) (${Math.round(p.ms / 1000)} s)`); } catch { /* partial line */ }
      }
    });
    child.stderr.on('data', (chunk) => { err += chunk; });
    child.on('error', reject);
    child.on('close', (code) => {
      if (code !== 0) { reject(new Error(`the ${tier} child for ${ids.join(',')} exited ${code}: ${err.split('\n').filter((l) => !/warning/i.test(l)).slice(-6).join(' | ')}`)); return; }
      resolve(out.split('\n').filter((l) => l.startsWith('PLAN ')).map((l) => JSON.parse(l.slice(5))));
    });
  });
}

/** Every map's four plan keys, recorded over `workers` children (half of them per tier). */
async function recordPlan(ids, workers = Math.max(2, Math.min(4, Math.floor(availableParallelism() / 4)))) {
  const perTier = Math.max(1, Math.floor(workers / 2));
  const jobs = [];
  for (const tier of ['desktop', 'mobile']) {
    for (let w = 0; w < perTier; w++) {
      const share = ids.filter((_, index) => index % perTier === w);
      if (share.length) jobs.push(runChild(tier, share));
    }
  }
  const recorded = {};
  for (const lines of await Promise.all(jobs)) for (const p of lines) (recorded[p.mapId] ||= {})[p.variant] = p.rows;
  for (const mapId of ids) {
    for (const variant of WRECK_PLAN_VARIANTS) if (!recorded[mapId]?.[variant]) throw new Error(`${mapId}@${variant} was not recorded`);
  }
  return recorded;
}

if (isMainModule(import.meta.url)) {
  const opt = Object.fromEntries(process.argv.slice(2).map((a) => { const m = /^--([a-z-]+)(?:=(.*))?$/.exec(a); return m ? [m[1], m[2] ?? true] : [a, true]; }));
  const { MAP_IDS } = await import('../src/world/maps/mapIds.ts');
  const ids = !opt.maps || opt.maps === 'all' ? [...MAP_IDS] : String(opt.maps).split(',').filter(Boolean);
  if (opt.record) {
    if (!['desktop', 'mobile'].includes(opt.tier)) { console.error('--record needs --tier=desktop|mobile'); process.exit(2); }
    await recordTier(opt.tier, ids);
    process.exit(0);
  }
  const recorded = await recordPlan(ids, opt.workers ? Math.max(2, Number(opt.workers)) : undefined);
  const fresh = planTables(recorded);
  if (opt.check) {
    const committed = committedTables();
    let drifted = 0;
    for (const mapId of ids) {
      for (const variant of WRECK_PLAN_VARIANTS) {
        const want = resolvePlanRows(fresh, mapId, variant), have = resolvePlanRows(committed, mapId, variant);
        if (sameRows(want, have)) console.log(`${mapId}@${variant}: current`);
        else { drifted++; console.log(`${mapId}@${variant}: DRIFTED (committed ${rowsText(have ?? [])}, the tree ${rowsText(want ?? [])})`); }
      }
    }
    if (drifted) { console.error(`[wreck-bake-plan] ${drifted} stale: node tools/wreck-bake-plan.mjs --write --maps=<ids>`); process.exit(1); }
    console.error(`[wreck-bake-plan] the committed plan holds (${ids.length} maps, ${WRECK_PLAN_VARIANTS.length} keys each)`);
  } else if (opt.write) {
    let tables = fresh;
    if (ids.length < MAP_IDS.length) {
      // a partial run keeps the other maps' rows (and drops the recorded maps' old variants)
      const committed = committedTables();
      const keep = (key) => !ids.includes(key.split('@')[0]);
      tables = {
        plan: { ...Object.fromEntries(Object.entries(committed.plan).filter(([k]) => keep(k))), ...fresh.plan },
        variants: { ...Object.fromEntries(Object.entries(committed.variants).filter(([k]) => keep(k))), ...fresh.variants },
      };
    }
    writeFileSync(PLAN_FILE, renderWreckBakePlan(tables));
    console.error(`[wreck-bake-plan] wrote ${Object.keys(tables.plan).length} map(s), ${Object.keys(tables.variants).length} variant row(s)`);
  } else {
    console.log(JSON.stringify(fresh, null, 1));
  }
  process.exit(0);
}
