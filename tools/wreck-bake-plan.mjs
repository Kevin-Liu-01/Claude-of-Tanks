#!/usr/bin/env node
// The wreck bake plan (2026-10-07, the time-to-battle lane): per map, the wreck bakes its props build requests of the
// wreck worker, in order — recorded in Node by draining the worker-wreck build with each request answered by the
// worker's own bake (the same donor build, pose and paint, through the same wire), as the browser would. The browser
// starts these bakes when the world build starts, beside the terrain and vegetation (src/world/wreckBakePrefetch.ts);
// a request the plan does not hold is baked where it is asked, so a stale plan costs time, never a different wreck.
//
//   node tools/wreck-bake-plan.mjs [--maps=all|<id,...>] [--write]   records (and with --write rewrites the plan)
//   node tools/wreck-bake-plan.mjs --check [--maps=...]               fails when the committed plan differs
import { readFileSync, writeFileSync } from 'node:fs';
import { installWorldBuildFixture } from './headlessWorldCollision.mjs';
import { isMainModule } from './map-probe-runtime.mjs';

const PLAN_FILE = new URL('../src/world/maps/wreckBakePlan.ts', import.meta.url);

export function renderWreckBakePlan(plan) {
  const lines = [
    '// Generated by tools/wreck-bake-plan.mjs — do not edit. The wreck bakes each map\'s props build requests of the',
    '// wreck worker (desktop tier, the standard terrain), in order: [donor spec, seed, ammo-rack pop]. The world build',
    '// starts them beside the terrain and vegetation (src/world/wreckBakePrefetch.ts); any other request bakes on demand.',
    'export const WRECK_BAKE_PLAN: Readonly<Record<string, ReadonlyArray<readonly [string, number, 0 | 1]>>> = {',
  ];
  for (const mapId of Object.keys(plan).sort()) {
    const rows = plan[mapId].map((r) => `['${r.specId}', ${r.seed}, ${r.pop ? 1 : 0}]`);
    lines.push(`  ${/^[a-z_][a-z0-9_]*$/.test(mapId) ? mapId : `'${mapId}'`}: [${rows.join(', ')}],`);
  }
  lines.push('};', '');
  return lines.join('\n');
}

export async function recordPlan(maps) {
  installWorldBuildFixture();
  const [mapsMod, idsMod, terrain, vegetation, props, fleet, models, wrecks, wire] = await Promise.all([
    import('../src/world/maps/index.ts'), import('../src/world/maps/mapIds.ts'), import('../src/world/terrain.ts'),
    import('../src/world/vegetation.ts'), import('../src/world/props.ts'), import('../src/vehicles/fleetFactory.ts'),
    import('../src/world/propsModelStore.ts'), import('../src/world/wrecks.ts'), import('../src/world/wreckBakeWire.ts'),
  ]);
  await models.preloadPropModels();
  const ids = maps === 'all' ? [...idsMod.MAP_IDS] : maps.split(',');
  const engine = { anisotropy: 4, setupShadowMaterial() {} };
  const plan = {};
  for (const mapId of ids) {
    const t0 = Date.now();
    const config = mapsMod.getMapConfig(mapId);
    const field = terrain.createHeightField(1337, config);
    const flora = vegetation.createVegetation(field, engine, 2001, config);
    // the worker's own bake (src/world/wreckBakeWorker.ts): the donor's builders, the bake, the wire both ways
    const bake = async (specId, options) => {
      await fleet.ensureTankBuilder(specId);
      const baked = wrecks.bakeTankWreck({}, specId, options);
      if (!baked) return null;
      const { wire: packed } = wire.packWreckBake(baked);
      return wire.unpackWreckBake(packed);
    };
    plan[mapId] = await props.recordWreckBakeRequests(field, engine, 2002, config, flora, bake);
    console.log(`[wreck-bake-plan] ${mapId}: ${plan[mapId].length} bake(s) ${plan[mapId].map((r) => `${r.specId}${r.pop ? '+pop' : ''}`).join(' ')} (${Math.round((Date.now() - t0) / 1000)} s)`);
  }
  return plan;
}

if (isMainModule(import.meta.url)) {
  const opt = Object.fromEntries(process.argv.slice(2).map((a) => { const m = /^--([a-z-]+)(?:=(.*))?$/.exec(a); return m ? [m[1], m[2] ?? true] : [a, true]; }));
  const plan = await recordPlan(opt.maps ?? 'all');
  if (opt.check) {
    const committed = readFileSync(PLAN_FILE, 'utf8');
    const stale = Object.keys(plan).filter((mapId) => {
      const row = committed.split('\n').find((l) => l.trimStart().startsWith(`${mapId}:`) || l.trimStart().startsWith(`'${mapId}':`));
      return !row || !row.includes(renderWreckBakePlan({ [mapId]: plan[mapId] }).split('\n').find((l) => l.includes(`${mapId}:`) || l.includes(`'${mapId}':`)).trim());
    });
    if (stale.length) { console.error(`[wreck-bake-plan] stale for ${stale.join(', ')}: run node tools/wreck-bake-plan.mjs --write`); process.exit(1); }
    console.log('[wreck-bake-plan] the committed plan holds');
  } else if (opt.write) {
    let merged = plan;
    if ((opt.maps ?? 'all') !== 'all') {
      // a partial run keeps the other maps' rows
      const { WRECK_BAKE_PLAN } = await import('../src/world/maps/wreckBakePlan.ts').catch(() => ({ WRECK_BAKE_PLAN: {} }));
      merged = Object.fromEntries(Object.entries(WRECK_BAKE_PLAN).map(([k, rows]) => [k, rows.map(([specId, seed, pop]) => ({ specId, seed, pop: !!pop }))]));
      Object.assign(merged, plan);
    }
    writeFileSync(PLAN_FILE, renderWreckBakePlan(merged));
    console.log(`[wreck-bake-plan] wrote ${Object.keys(merged).length} map(s)`);
  }
  process.exit(0);
}
