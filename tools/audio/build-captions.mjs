#!/usr/bin/env node
// tools/audio/build-captions.mjs — the crew radio's caption tables from its script (brand-ui SPEC 10, 14; PLAN BUI-F9).
// Copyright © 2026 Kevin B. Liu.
//
// tools/audio/crew-lines.json is the crew radio script: per line id the speaking role and the takes in every crew
// language, parallel by index (take n says the same thing in each). Captions show who spoke and what they said in the
// player's language, whatever language the crew speaks, so this writes two tables:
//   src/audio/captionSpeakers.generated.ts  line id -> speaking role (commander, gunner, loader, driver): the caption
//                                            stream (src/audio/captions.ts) names the speaker with it
//   src/audio/captionScript.generated.ts    line id -> its en-US and zh-CN takes: the caption renderer loads it lazily
//                                            and shows take n of the transmission the crew keyed
//
//   node tools/audio/build-captions.mjs           write both files (pure: the same script always gives the same bytes)
//   node tools/audio/build-captions.mjs --check   exit 1 when either file drifts from the script
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');
export const CREW_LINES = join(HERE, 'crew-lines.json');
export const SPEAKERS_TS = join(ROOT, 'src', 'audio', 'captionSpeakers.generated.ts');
export const SCRIPT_TS = join(ROOT, 'src', 'audio', 'captionScript.generated.ts');
/** The caption languages and the script column each reads. */
const CAPTION_LOCALES = Object.freeze({ 'en-US': 'en-US', 'zh-CN': 'zh' });
const ROLES = Object.freeze(['commander', 'gunner', 'loader', 'driver']);

const HEADER = `// Generated by tools/audio/build-captions.mjs from tools/audio/crew-lines.json. Do not edit by hand:
// edit the script and run \`node tools/audio/build-captions.mjs\`. Copyright © 2026 Kevin B. Liu.
`;
const str = (s) => JSON.stringify(s);
const key = (id) => (/^[a-z_$][a-z0-9_$]*$/i.test(id) ? id : str(id));

/** Both generated files keyed by path; throws on a line without a known role or with uneven takes. */
export function generate(script = JSON.parse(readFileSync(CREW_LINES, 'utf8'))) {
  const lines = [...script.lines].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  for (const line of lines) {
    if (!ROLES.includes(line.role)) throw new Error(`build-captions: ${line.id} has no known role (${line.role})`);
    const counts = Object.values(CAPTION_LOCALES).map((column) => line[column]?.length ?? 0);
    if (counts.some((n) => n === 0 || n !== counts[0])) {
      throw new Error(`build-captions: ${line.id} needs the same number of takes in ${Object.values(CAPTION_LOCALES).join(' and ')}`);
    }
  }
  const speakers = `${HEADER}// The speaking crew role of every radio line: src/audio/captions.ts names a transmission's speaker with it.

export type CaptionSpeaker = ${ROLES.map(str).join(' | ')};

export const CAPTION_SPEAKERS: Readonly<Record<string, CaptionSpeaker>> = {
${lines.map((line) => `  ${key(line.id)}: ${str(line.role)},`).join('\n')}
};
`;
  const scriptTs = `${HEADER}// What every radio line says in the caption languages, take by take (take n is the same call in every crew language),
// for the caption renderer, which loads this with its own chunk.

export const CAPTION_SCRIPT: Readonly<Record<string, Readonly<Record<${Object.keys(CAPTION_LOCALES).map(str).join(' | ')}, readonly string[]>>>> = {
${lines.map((line) => `  ${key(line.id)}: {\n${Object.entries(CAPTION_LOCALES)
    .map(([locale, column]) => `    ${str(locale)}: [${line[column].map(str).join(', ')}],`).join('\n')}\n  },`).join('\n')}
};
`;
  return { [SPEAKERS_TS]: speakers, [SCRIPT_TS]: scriptTs };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const check = process.argv.includes('--check');
  const drift = [];
  for (const [path, text] of Object.entries(generate())) {
    let current = null;
    try { current = readFileSync(path, 'utf8'); } catch { /* missing counts as drift */ }
    if (current === text) continue;
    if (check) drift.push(path.slice(ROOT.length + 1));
    else writeFileSync(path, text);
  }
  if (drift.length) {
    console.error(`build-captions: ${drift.join(', ')} drifted from tools/audio/crew-lines.json; run node tools/audio/build-captions.mjs`);
    process.exitCode = 1;
  } else {
    console.log(check ? 'build-captions: caption tables match the crew script' : 'build-captions: caption tables written');
  }
}
