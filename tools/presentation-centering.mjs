#!/usr/bin/env node
// Deterministic rendered-pixel census for neutral vehicle presentation.
//
//   node tools/presentation-centering.mjs --check
//   node tools/presentation-centering.mjs --check --ids=m46_patton,m47_patton
//   node tools/presentation-centering.mjs --update
//   node tools/presentation-centering.mjs --update --ids=a,b  # then regenerate selected images
//   node tools/presentation-centering.mjs --sync-assets --ids=a,b

import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { resolve, sep } from 'node:path';
import { createServer } from 'vite';
import puppeteer from 'puppeteer';
import { presentationNumberSource as numberSource, presentationReceiptErrors, syncAssetProjectionSource, updateSelectedPresentationSource } from './presentation-receipt.mjs';
import { TANK_PRESENTATION_ANCHORS, TANK_PRESENTATION_PROJECTIONS } from '../src/vehicles/presentationAnchors.generated.ts';

const args = process.argv.slice(2);
const update = args.includes('--update');
const check = args.includes('--check');
const syncAssets = args.includes('--sync-assets');
if (Number(update) + Number(check) + Number(syncAssets) !== 1) {
  console.error('usage: node tools/presentation-centering.mjs (--check | --update | --sync-assets) [--ids=a,b]');
  process.exit(2);
}

function opt(name, fallback = '') {
  const prefix = `--${name}=`;
  const inline = args.find((arg) => arg.startsWith(prefix));
  if (inline) return inline.slice(prefix.length);
  const index = args.indexOf(`--${name}`);
  return index >= 0 ? args[index + 1] : fallback;
}

const selectedIds = opt('ids').split(',').map((id) => id.trim()).filter(Boolean);
if (args.some(arg => arg === '--ids' || arg.startsWith('--ids=')) && !selectedIds.length) {
  console.error('[presentation-centering] an explicit --ids scope must not be empty');
  process.exit(2);
}
if (syncAssets && !selectedIds.length) {
  console.error('[presentation-centering] --sync-assets requires explicit --ids=a,b');
  process.exit(2);
}

const root = process.cwd();
const outputPath = resolve(root, 'src/vehicles/presentationAnchors.generated.ts');
const originalSource = readFileSync(outputPath, 'utf8');
const cacheDir = resolve('/tmp', `cot-centering-vite-${process.pid}`);
const MAX_RESIDUAL_PX = 0.25;
const MAX_EXPORTED_RESIDUAL_PX = 0.5;

function generatedSource(rows) {
  const records = Object.keys(rows).sort().map((id) => (
    `  ${id}: Object.freeze({ xM: ${numberSource(rows[id].xM)}, zM: ${numberSource(rows[id].zM)} }),`
  ));
  const projections = Object.keys(rows).sort().map((id) => {
    const projection = rows[id].projection;
    return `  ${id}: Object.freeze({ centerYM: ${numberSource(projection.centerYM)}, `
      + `topHalfM: ${numberSource(projection.topHalfM)}, sideHalfM: ${numberSource(projection.sideHalfM)} }),`;
  });
  return [
    '// Generated by tools/presentation-centering.mjs from finished top-down body masks.',
    '// Do not hand-edit. Cannon/antenna-width rows are excluded before the opaque',
    "// pixel centroid is converted back into the tank rig's local X/Z coordinates.",
    '',
    'export interface TankPresentationAnchor {',
    '  readonly xM: number;',
    '  readonly zM: number;',
    '}',
    '',
    'export interface TankPresentationProjection {',
    '  readonly centerYM: number;',
    '  readonly topHalfM: number;',
    '  readonly sideHalfM: number;',
    '}',
    '',
    'export const TANK_PRESENTATION_ANCHOR_SCHEMA_VERSION = 2;',
    '',
    'export const TANK_PRESENTATION_ANCHORS: Readonly<Record<string, TankPresentationAnchor>> = Object.freeze({',
    ...records,
    '});',
    '',
    'export function presentationAnchorFor(id: string): TankPresentationAnchor | null {',
    '  return TANK_PRESENTATION_ANCHORS[id] || null;',
    '}',
    '',
    '// Exact orthographic fit envelopes shared with tools/icons-page.html.',
    '// Hit markers consume these receipts so they overlay the generated assets',
    '// without re-deriving scale from symmetric published dimensions.',
    'export const TANK_PRESENTATION_PROJECTIONS: Readonly<Record<string, TankPresentationProjection>> = Object.freeze({',
    ...projections,
    '});',
    '',
    'export function presentationProjectionFor(id: string): TankPresentationProjection | null {',
    '  return TANK_PRESENTATION_PROJECTIONS[id] || null;',
    '}',
    '',
  ].join('\n');
}

const server = await createServer({
  root,
  configFile: false,
  cacheDir,
  logLevel: 'error',
  optimizeDeps: { noDiscovery: true },
  server: {
    host: '127.0.0.1',
    port: 7600 + (process.pid % 200),
    strictPort: true,
    hmr: false,
    watch: null,
  },
});
await server.listen();
const address = server.httpServer.address();
const port = typeof address === 'object' && address ? address.port : server.config.server.port;
const browser = await puppeteer.launch({
  headless: 'new',
  protocolTimeout: 15 * 60 * 1000,
  args: ['--use-gl=angle', '--enable-webgl', '--no-sandbox', '--disable-dev-shm-usage'],
});
const page = await browser.newPage();
const pageErrors = [];
page.on('pageerror', (error) => pageErrors.push(String(error)));
page.on('console', (message) => {
  if (message.type() === 'error' && !message.text().includes('favicon')
      && !message.text().includes('404')) {
    pageErrors.push(message.text());
  }
});

let failed = false;
try {
  const url = `http://127.0.0.1:${port}/tools/icons-page.html`;
  await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 30000 });
  await page.waitForFunction('window.__ICONS_READY === true', { timeout: 60000 });
  const fleetIds = await page.evaluate(() => [...window.__FLEET_IDS]);
  const unknown = selectedIds.filter((id) => !fleetIds.includes(id));
  if (unknown.length) throw new Error(`unknown tank id(s): ${unknown.join(', ')}`);
  const ids = selectedIds.length ? selectedIds : fleetIds;
  // Match the asset generator's two-pass lifecycle. The warm pass settles
  // deferred vehicle materials/attachments before either tool measures the
  // finished top render; auditing a cold one-off build allowed a few cached
  // fleet variants to disagree with their generated images.
  await page.evaluate((tankIds) => window.__WARM(tankIds), ids);
  await page.waitForFunction(
    () => {
      window.__CENTER_POLLS = (window.__CENTER_POLLS || 0) + 1;
      const stats = window.__GLB_STATS;
      if (!stats) return window.__CENTER_POLLS >= 10;
      const settled = stats.started === stats.settled;
      window.__CENTER_SETTLE_STREAK = settled
        ? (window.__CENTER_SETTLE_STREAK || 0) + 1 : 0;
      return window.__CENTER_SETTLE_STREAK >= 2;
    },
    { timeout: 120000, polling: 400 },
  );
  const rows = {};
  for (let i = 0; i < ids.length; i += 12) {
    const chunk = ids.slice(i, i + 12);
    Object.assign(rows, await page.evaluate((tankIds) => window.__CENTER_AUDIT(tankIds), chunk));
  }

  const errors = Object.entries(rows).filter(([, row]) => row.error);
  if (errors.length) {
    throw new Error(errors.map(([id, row]) => `${id}: ${row.error}`).join('\n'));
  }
  const ranked = Object.entries(rows)
    .map(([id, row]) => ({ id, ...row }))
    .sort((a, b) => b.residualPx - a.residualPx);
  const maximum = ranked[0];

  if (update) {
    const updated = selectedIds.length
      ? updateSelectedPresentationSource(originalSource, ids, rows, TANK_PRESENTATION_ANCHORS, TANK_PRESENTATION_PROJECTIONS)
      : generatedSource(rows);
    if (pageErrors.length || readFileSync(outputPath, 'utf8') !== originalSource) {
      throw new Error('capture errors or concurrent generated-source change; no anchor written');
    }
    writeFileSync(outputPath, updated);
    console.log(`[presentation-centering] wrote ${ids.length} rendered anchors -> ${outputPath}`);
    console.log('[presentation-centering] regenerate affected assets and run --check; generation is not release qualification');
  } else {
    const receiptErrors = check ? ids.flatMap(id => presentationReceiptErrors(id,
      rows[id]?.currentAnchor, rows[id]?.capturedProjection,
      TANK_PRESENTATION_ANCHORS[id], TANK_PRESENTATION_PROJECTIONS[id])) : [];
    if (receiptErrors.length) {
      const recovery = selectedIds.length
        ? `regenerate stale selected assets, or use --sync-assets --ids=${ids.join(',')} only when their saved captures are current`
        : 'run npm run tank:centering:update';
      throw new Error(`${receiptErrors.join('\n')}; ${recovery}`);
    }
    if (!selectedIds.length) {
      const expected = generatedSource(rows);
      const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
      if (current !== expected) {
        throw new Error('rendered anchor receipts are stale; run npm run tank:centering:update');
      }
    }
    const offCenter = ranked.filter((row) => row.residualPx > MAX_RESIDUAL_PX);
    if (offCenter.length) {
      throw new Error(`rendered center exceeds ${MAX_RESIDUAL_PX}px:\n${offCenter.slice(0, 20)
        .map((row) => `  ${row.id}: ${row.residualPx}px (${row.deltaM}m)`).join('\n')}`);
    }
    const exportedRows = {};
    for (let i = 0; i < ids.length; i += 24) {
      const chunk = ids.slice(i, i + 24);
      Object.assign(exportedRows, await page.evaluate(
        (tankIds) => window.__TOP_ASSET_CENTER_AUDIT(tankIds), chunk,
      ));
    }
    const exportedErrors = Object.entries(exportedRows).filter(([, row]) => row.error);
    if (exportedErrors.length) {
      throw new Error(exportedErrors.map(([id, row]) => `${id}: ${row.error}`).join('\n'));
    }
    const exportedRanked = Object.entries(exportedRows)
      .map(([id, row]) => ({ id, ...row }))
      .sort((a, b) => b.residualPx - a.residualPx);
    const exportedMaximum = exportedRanked[0];
    const exportedOffCenter = exportedRanked
      .filter((row) => row.residualPx > MAX_EXPORTED_RESIDUAL_PX);
    if (exportedOffCenter.length) {
      throw new Error(`exported top center exceeds ${MAX_EXPORTED_RESIDUAL_PX}px:\n`
        + exportedOffCenter.slice(0, 20).map((row) => `  ${row.id}: ${row.residualPx}px `
        + `(x ${row.deltaXPx}px, y ${row.deltaYPx}px)`).join('\n'));
    }
    if (syncAssets) {
      const before = readFileSync(outputPath, 'utf8');
      const iconsRoot = resolve(root, 'public/icons');
      const manifest = JSON.parse(readFileSync(resolve(iconsRoot, 'tank-assets.json'), 'utf8'));
      const live = await page.evaluate(tankIds => window.__AUDIT(tankIds), ids);
      const captureErrors = ids.flatMap(id => presentationReceiptErrors(id,
        rows[id]?.currentAnchor, rows[id]?.capturedProjection,
        live.tanks[id]?.presentationAnchor, live.tanks[id]?.presentationProjection));
      if (captureErrors.length) throw new Error(captureErrors.join('\n'));
      const next = syncAssetProjectionSource(before, ids, manifest, live, TANK_PRESENTATION_ANCHORS, file => {
        const target = resolve(iconsRoot, file);
        if (!target.startsWith(`${iconsRoot}${sep}`)) throw new Error('asset path escapes icons directory');
        return readFileSync(target);
      });
      if (pageErrors.length || readFileSync(outputPath, 'utf8') !== before) {
        throw new Error('capture errors or concurrent generated-source change; no projection written');
      }
      writeFileSync(outputPath, next);
      console.log(`[presentation-centering] synced ${ids.length} hash-verified saved/native projections; all anchors and unselected rows retained`);
    }
    console.log(`[presentation-centering] PASS ${ids.length} tanks; maximum rendered residual `
      + `${maximum.residualPx.toFixed(2)} px (${maximum.id}); maximum exported top residual `
      + `${exportedMaximum.residualPx.toFixed(2)} px (${exportedMaximum.id})`);
  }
} catch (error) {
  failed = true;
  console.error(`[presentation-centering] FAIL: ${error.message}`);
} finally {
  if (pageErrors.length) {
    failed = true;
    console.error(`[presentation-centering] page errors (${pageErrors.length}):`);
    for (const error of pageErrors.slice(0, 20)) console.error(`  ${error}`);
  }
  await browser.close();
  await server.close();
  rmSync(cacheDir, { recursive: true, force: true });
}

process.exit(failed ? 1 : 0);
