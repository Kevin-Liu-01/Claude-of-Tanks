// Bake one exact first-party vehicle shadow proxy into a tiny Garage-only
// background asset. Runtime Garage code gets the authored silhouette without
// importing a fleet builder or constructing a live/wrecked tank.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { ensureTankBuilder } from '../src/vehicles/fleetFactory.ts';
import { bakeTankWreck } from '../src/world/wrecks.ts';

const SOURCE_SPEC_ID = 'm1a2';
const SEED = 4812;
const outputUrl = new URL('../src/ui/garageWreckGeometry.generated.ts', import.meta.url);

await ensureTankBuilder(SOURCE_SPEC_ID);
const wreck = bakeTankWreck(null, SOURCE_SPEC_ID, { seed: SEED, pop: false });
if (!wreck?.shadowGeo) throw new Error('Garage wreck source did not expose its authored shadow proxy');

const source = wreck.shadowGeo.getAttribute('position');
const millimeters = new Int16Array(source.count * 3);
for (let index = 0; index < millimeters.length; index += 1) {
  const value = Math.round(Number(source.array[index]) * 1000);
  if (value < -32768 || value > 32767) throw new Error(`Garage wreck coordinate overflow at ${index}`);
  millimeters[index] = value;
}
const encoded = Buffer.from(millimeters.buffer).toString('base64');
const generated = `// GENERATED by tools/generate-garage-wreck-asset.mjs. Do not edit.\n\n`
  + `export const GARAGE_WRECK_ASSET = Object.freeze({\n`
  + `  sourceSpecId: '${SOURCE_SPEC_ID}',\n`
  + `  seed: ${SEED},\n`
  + `  sourceTriangles: ${wreck.tris},\n`
  + `  triangles: ${source.count / 3},\n`
  + `  millimetersBase64: '${encoded}',\n`
  + `});\n`;

wreck.geo.dispose();
wreck.shadowGeo.dispose();

const outputPath = fileURLToPath(outputUrl);
if (process.argv.includes('--check')) {
  const existing = await readFile(outputPath, 'utf8');
  if (existing !== generated) {
    throw new Error('Garage wreck proxy is stale; run npm run garage:wreck:update');
  }
  console.log(`garage wreck proxy: current (${SOURCE_SPEC_ID}, ${source.count / 3} triangles)`);
} else {
  await writeFile(outputPath, generated);
  console.log(`wrote ${outputPath} (${SOURCE_SPEC_ID}, ${source.count / 3} triangles)`);
}
