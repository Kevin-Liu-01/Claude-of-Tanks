import puppeteer from 'puppeteer';
import { createServer } from 'vite';
import { writeFileSync } from 'node:fs';
const vite = await createServer({ server: { port: 5603 }, logLevel: 'silent' });
await vite.listen();
const browser = await puppeteer.launch({ headless: 'new', args: ['--no-sandbox', '--use-angle=metal'] });
const page = await browser.newPage();
const errs = [];
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text().slice(0, 300)); });
await page.setViewport({ width: 1920, height: 1080, deviceScaleFactor: 1 });
await page.goto('http://localhost:5603/', { waitUntil: 'domcontentloaded' });
await page.waitForFunction('window.__GAME_READY === true', { timeout: 120000 });
await page.evaluate("window.__SHOTS.set('explosion')");
await new Promise((r) => setTimeout(r, 1600));
writeFileSync(process.argv[2] || 'shots/_lp5b_ex_check.png', await page.screenshot({ type: 'png' }));
console.log('errors:', errs.length ? errs.join('\n') : 'none');
await browser.close();
await vite.close();
