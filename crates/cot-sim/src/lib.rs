//! cot-sim — the deterministic simulation core of Claude of Tanks, ported
//! from `src/sim` (docs/PORT-BEVY.md).
//!
//! Rules this crate lives by (they mirror docs/ARCHITECTURE.md §1):
//! - metres / seconds / radians; tank forward is local +Z; +Y is up;
//! - no wall-clock time, no ambient randomness: time arrives as `dt`,
//!   randomness as an injected [`rng::Mulberry32`] (bit-identical to the
//!   TypeScript `mulberry32`);
//! - no engine, window, GPU or network dependency — the same crate drives the
//!   browser client and the dedicated server;
//! - every arithmetic path keeps the TypeScript operation order so the golden
//!   vectors in `tests/golden/*.json` (generated by
//!   `tools/port-golden-vectors.mjs` from the TypeScript source of truth)
//!   compare bit-for-bit; transcendental functions go through [`jsmath`],
//!   never through `std`'s platform-dependent `f64` methods.

#![forbid(unsafe_code)]
#![warn(missing_docs)]

pub mod ballistics;
pub mod contact;
pub mod deformation;
pub mod grid;
pub mod jsmath;
pub mod math;
pub mod records;
pub mod rng;
pub mod structure_support;
pub mod support_sampling;

/// The fixed simulation step (docs/ARCHITECTURE.md §1: `SIM_DT = 1/60`).
pub const SIM_DT: f64 = 1.0 / 60.0;
